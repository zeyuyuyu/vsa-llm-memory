"""B52 part (a) verdict (prereg/B52_robustness_layers_maps_1day_prereg.md). Written before any B52 test output exists.

The seven B42 label-free interfaces on Qwen3-8B's dev-chosen B31 exploratory layer (C: layer 27, A: layer 9) and on the
input embeddings (layer 0), against the naming head read from the SAME layer. Every test accuracy is recomputed from
the saved per-instance outputs against labels regenerated by b31_struct (b42_verdict.memory_arm / probe_arm) and
compared with the logged value. F = B31's equalised probe (final layer; the floor B42 used); N = the naming head
(perm, named) at the cell's layer (B31 explore1 for layers 9 / 27; B52's run for layer 0).

  python b52_verdict_a.py --root /path/to/work/b52/out --b31 /path/to/work/b31/out --out results/b52a_verdict.txt
"""
import argparse, json, os, sys
from datetime import datetime

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import b31_struct as S                                                      # noqa: E402
import b42_verdict as V                                                     # noqa: E402

CELLS = [("qwen8L27", "C"), ("qwen8L0", "C"), ("qwen8L9", "A"), ("qwen8L0", "A")]
LAYER = {"qwen8L27": "layer 27", "qwen8L9": "layer 9", "qwen8L0": "input embeddings"}
LF = ["vq", "dkvb", "gumbel", "st", "cw", "bind+pc", "bind+pz"]
PRIMARY = "perm/named"
L = []


def P(s=""):
    L.append(s); print(s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="/path/to/work/b52/out")
    ap.add_argument("--b31", default="/path/to/work/b31/out")
    ap.add_argument("--out", default="results/b52a_verdict.txt")
    ap.add_argument("--scores", default="results/b52a_scores.json")
    ap.add_argument("--cells", default=",".join("%s_%s" % c for c in CELLS),
                    help="cells to report (compute note 2: only qwen8L27_C ran; the others are 'not run')")
    a = ap.parse_args()

    run_cells = a.cells.split(",")
    CELLS[:] = [c for c in list(CELLS) if "%s_%s" % c in run_cells]
    R, R31 = a.root, a.b31
    P("# B52 (a) verdict (prereg/B52_robustness_layers_maps_1day_prereg.md): B42's label-free interfaces on Qwen3-8B's")
    P("# dev-chosen intermediate layer and input embeddings. Generated by b52_verdict_a.py on %s UTC."
      % datetime.utcnow().strftime("%Y-%m-%d %H:%M"))
    P("# Cells reported: %s; NOT RUN (compute note 2, deadline): %s" % (", ".join("%s_%s" % c for c in CELLS), ", ".join(
        "%s_%s" % c for c in [("qwen8L27", "C"), ("qwen8L0", "C"), ("qwen8L9", "A"), ("qwen8L0", "A")] if c not in CELLS) or "none"))
    ST = {ar: S.build(ar, "test") for ar in "AC"}
    Y = {ar: np.array([s["label"] for s in ST[ar]]) for ar in "AC"}
    sel = V.load(os.path.join(R, "select.json")) or {}
    out = {"cells": {}}
    P("\n## Dev selections (seed 42, train + dev only; best-epoch dev accuracy, perm/named)")
    for enc, ar in CELLS:
        k = "%s_%s" % (enc, ar)
        b = sel.get("bind", {}).get(k)
        if b:
            P("  %-12s binding-loss lr %g (dev %s)" % (k, b["pick"]["cfg"]["lr"], ", ".join(
                "lr %g %.3f" % (r["cfg"]["lr"], r["dev"]) for r in b["rows"])))
        for fam in ["vq", "dkvb", "gumbel", "st", "cw"]:
            v = sel.get(fam, {}).get(k)
            if v:
                P("  %-12s %-7s %s dev %.3f (epoch %d) of %d configurations" % (
                    k, fam, json.dumps(v["cfg"]), v["dev"], v["epoch"], len(sel["grids"][fam][k])))
    P("\n## Gate G1 (labelled positive control, dev): gumbel / st code path + identity loss within 0.02 of the")
    P("## naming head's best dev on the same cell")
    for enc, ar in CELLS:
        k = "%s_%s" % (enc, ar)
        nmp = os.path.join(R31, "explore1", "%s_name.json" % k) if enc != "qwen8L0" else os.path.join(R, "name", "%s_name.json" % k)
        nm = V.load(nmp)
        ndev = max(e["%s:dev" % PRIMARY]["acc"] for e in nm["runs"][0]["epochs"]) if nm else None
        for fam in ("gumbel", "st"):
            g1 = V.load(os.path.join(R, "g1", "%s_%s_g1.json" % (k, fam)))
            if g1 and ndev is not None:
                gd = max(e["%s:dev" % PRIMARY]["acc"] for e in g1["runs"][0]["epochs"])
                ok = gd >= ndev - 0.02
                out.setdefault("G1", {})["%s_%s" % (k, fam)] = ok
                P("  G1 %-12s %-6s best dev %.3f vs naming head %.3f  %s" % (k, fam, gd, ndev, "PASS" if ok else "FAIL"))
    P("\n## Results: test accuracy per seed (42/123/456) [Wilson 95%], mean [bootstrap 95%]; recovery R = (mean - F) /")
    P("## (N - F); F = B31 equalised probe (final layer), N = naming head (perm, named) read from the SAME layer")
    BAR = {}
    for enc, ar in CELLS:
        k = "%s_%s" % (enc, ar)
        y = Y[ar]
        Fr = V.probe_arm(os.path.join(R31, "probe_final", "qwen8_%s.json" % ar), y)
        nmp = os.path.join(R31, "explore1", "%s_name.json" % k) if enc != "qwen8L0" else os.path.join(R, "name", "%s_name.json" % k)
        Nr = V.memory_arm(nmp, PRIMARY, y)
        Nfin = V.memory_arm(os.path.join(R31, "arms_final", "qwen8_%s_name.json" % ar), PRIMARY, y)
        arms = {}
        for fam in ["vq", "dkvb", "gumbel", "st", "cw"]:
            arms[fam] = V.memory_arm(os.path.join(R, "final", "%s_%s.json" % (k, fam)), PRIMARY, y)
        for rd, kk in ((PRIMARY, "bind"), (PRIMARY + "+pc", "bind+pc"), (PRIMARY + "+pz", "bind+pz")):
            arms[kk] = V.memory_arm(os.path.join(R, "final", "%s_bind.json" % k), rd, y)
        P("\n  %s, arena %s (n = %d)" % (LAYER[enc], ar, len(y)))
        if not (Fr and Nr):
            P("    references missing"); continue
        gap = Nr["mean"] - Fr["mean"]
        P("    floor F %.3f, naming head at this layer N %.3f [%.3f-%.3f] (seeds %s), gap %.3f%s; (final-layer naming head %s)"
          % (Fr["mean"], Nr["mean"], Nr["ci"][0], Nr["ci"][1], "/".join(V.f3(x) for x in Nr["acc"]), gap,
             "" if gap >= 0.10 else " (< 0.10: recovery undefined)", V.f3(Nfin["mean"]) if Nfin else "n/a"))
        if gap >= 0.10:
            P("    MATCH needs mean >= %.3f (with F at chance 0.5 instead: >= %.3f)" % (
                Fr["mean"] + 0.9 * gap, 0.5 + 0.9 * (Nr["mean"] - 0.5)))
        cell = {"F": Fr["mean"], "N": Nr["mean"], "N_ci": Nr["ci"], "N_seeds": Nr["acc"], "gap": gap, "arms": {}}
        for kk in LF + ["bind"]:
            r = arms.get(kk)
            if r is None:
                P("    %-9s missing" % kk); continue
            line = "    %-9s mean %s [%s-%s]  seeds %s" % (kk, V.f3(r["mean"]), V.f3(r["ci"][0]), V.f3(r["ci"][1]), ", ".join(
                "%s [%s-%s]" % (V.f3(x), V.f3(w[0]), V.f3(w[1])) for x, w in zip(r["acc"], r["wilson"])))
            if not r["recomputed_equals_logged"]:
                line += "  RECOMPUTED != LOGGED (logged %s)" % "/".join(V.f3(x) for x in r["logged"])
            P(line)
            rec = {"mean": r["mean"], "ci": r["ci"], "seeds": r["acc"], "logged": r["logged"]}
            extra = []
            if gap >= 0.10:
                Rb = (r["bm"] - Fr["bm"]) / (Nr["bm"] - Fr["bm"])
                Rm = (r["mean"] - Fr["mean"]) / gap
                Rs = [(x - Fr["mean"]) / gap for x in r["acc"]]
                lo, hi = V.ci(Rb)
                b_ = V.bar(Rm, Rs)
                rec.update({"R": Rm, "R_ci": [lo, hi], "R_seeds": Rs, "bar": b_ if kk in LF else "(reference)"})
                if kk in LF:
                    BAR[(k, kk)] = (b_, Rm, (lo, hi))
                extra.append("recovery %.3f [%.3f, %.3f] (seeds %s) -> %s" % (Rm, lo, hi, "/".join("%.2f" % x for x in Rs),
                                                                             b_ if kk in LF else "(reference)"))
            elif kk in LF:
                BAR[(k, kk)] = ("no headroom", None, None)
                extra.append("vs floor %+.3f, vs naming head %+.3f (no headroom)" % (r["mean"] - Fr["mean"], r["mean"] - Nr["mean"]))
            extra.append("vs the naming head at this layer %+.3f; vs the best naming head (any layer, B31 explore1 / final) "
                         "%+.3f" % (r["mean"] - Nr["mean"], r["mean"] - max(Nr["mean"], Nfin["mean"] if Nfin else 0)))
            if r.get("geom") and r["geom"][0]:
                extra.append("cross-talk different/same " + ", ".join(
                    "%s/%s" % (V.f3(g["different"]), V.f3(g["same"])) if g else "-" for g in r["geom"]))
                rec["geom"] = r["geom"]
            if r.get("disc") and r["disc"][0]:
                ds = r["disc"]
                extra.append("mention consistency %s, code purity %s, codes used %s%s" % (
                    "/".join(V.f3(x["consistency"]) for x in ds), "/".join(V.f3(x["purity"]) for x in ds),
                    "/".join(str(x["codes_used"]) for x in ds),
                    ("; hex/decimal alias rate " + "/".join(V.f3(x.get("alias_rate")) for x in ds)) if ar == "C" else ""))
                rec["disc"] = ds
            if r.get("wins") and r["wins"][0] is not None:
                hr = [V.hop_rates(ar, ST[ar], w) for w in r["wins"]]
                extra.append("clean-up correct at hop 1 / hop 2 / both: " + ", ".join(
                    "%s/%s/%s" % (V.f3(h[0]), V.f3(h[1]), V.f3(h[2])) for h in hr if h))
                rec["hops"] = hr
            if r.get("epoch"):
                extra.append("dev-selected epoch %s; dev %s; train %s; final-epoch test %s" % (
                    "/".join(str(x) for x in r["epoch"]), "/".join(V.f3(x) for x in r["dev"]),
                    "/".join(V.f3(x) for x in r["train"]), "/".join(V.f3(x) for x in r["final"])))
            for x in extra:
                P("              %s" % x)
            cell["arms"][kk] = rec
        out["cells"][k] = cell
    P("\n## Bar per cell: a label-free arm MATCHES if its mean recovery is >= 0.90 (PARTIAL >= 0.25, FAIL < 0.25)")
    ans = {}
    for enc, ar in CELLS:
        k = "%s_%s" % (enc, ar)
        rows = [(kk, BAR.get((k, kk))) for kk in LF]
        m = [kk for kk, r in rows if r and r[0].startswith("MATCHES")]
        p_ = [kk for kk, r in rows if r and r[0] == "PARTIAL"]
        ans[k] = {"match": m, "partial": p_, "complete": all(r for _, r in rows)}
        P("  %-12s %s" % (k, "; ".join("%s %s%s" % (kk, r[0], " (R %.3f [%.3f, %.3f])" % (r[1], r[2][0], r[2][1]) if r and r[1] is not None else "")
                                      if r else "%s n/a" % kk for kk, r in rows)))
        P("  %-12s -> a label-free interface reaches the naming head read from the same layer: %s%s" % (
            "", "YES (" + ", ".join(m) + ")" if m else ("PARTIAL (" + ", ".join(p_) + ")" if p_ else "NO"),
            "" if ans[k]["complete"] else " [incomplete]"))
    out["answer"] = ans
    P("\n## Second scorer (b42_indep.py on the B52 finals; out/indep52.json)")
    ind = V.load(os.path.join(R, "indep52.json"))
    if ind:
        for kk, v in sorted(ind.items()):
            P("  %-30s %s" % (kk, ", ".join("%s %s" % (x, V.f3(y) if isinstance(y, float) else y) for x, y in v.items())))
        out["indep"] = ind
    else:
        P("  missing")
    open(a.out, "w").write("\n".join(L) + "\n")
    json.dump(out, open(a.scores, "w"), indent=1, default=float)


if __name__ == "__main__":
    main()
