"""B31 structure layer (prereg/B31_encoder_equalised_baselines_prereg.md): the three arenas as TEXT plus the gold
structure of every symbol mention, independent of any tokenizer, so that the same instances can be read by two
frozen encoders (Phi-2, Qwen3-8B).

Every instance is generated by the B27 generators (verbatim arena modules in b27_arena/, md5-checked, through
b27_common): A = SystematicChainDataset rows (b27_common.gen_chain), B = v11.Arena rows (b27_common.make_b_arena), C =
v13.Arena rows. This file re-runs the same generator code with the same random streams and keeps the text; the
self-test (b31_prep.py selftest) checks, under the Phi-2 tokenizer, that the token ids equal the B27 rows and that the
token spans derived here equal the spans the published arms read (B, C: the rows' spans; A: the token scanner of
explicit_chain_models).

A mention is one written symbol: (key, kind, sym, cs, ce) with character span [cs, ce).
  kind  A: R / X / Y markers "[R3A]" (span = the whole marker, the published scanner's span), F fillers "{12}"
           (span = the digits);  B: R roles (span = the two hex digits), F fillers (digits);
        C: R roles (hex digits), F fillers (digits). In C roles and fillers share one 64-symbol codebook.
  key   identifies the same mention in the reshuffled second view (label-free InfoNCE arm), never an identity label.
Gold structure per instance:
  A: secA [(r, x)], secB [(x, y)], secC [(y, f)] as mention indices in text order; q (query R), cand (candidate F)
  B: ctx [(r, f)]; q (query role), cand
  C: lv [[(r, f)] level 0, [(r, f)] level 1]; q, cand
"""
import os, random, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import b27_common as BC                                                     # noqa: E402

N_SPLIT = BC.N_SPLIT                       # train, dev, test sizes: A 2000/500/1000, B 1000/500/500, C 800/500/500
MAXLEN_PHI2 = {"A": 512, "B": 768, "C": 768}   # the arenas' own max_length (padding target of the published rows)
ARENAS = ("A", "B", "C")

_MK = re.compile(r"\[([RXY])([0-9A-F]{2})\]")
_FL = re.compile(r"\{(\d+)\}")


def _mods():
    return BC.load_arena_modules()


# ------------------------------------------------------------------ arena A

def _a_struct(text, label):
    head, rest = text.split(" B ", 1)
    assert head.startswith("A ")
    b_txt, rest = rest.split(" C ", 1)
    c_txt, q_txt = rest.split(" Q ", 1)
    o_b = len(head) + 3
    o_c = o_b + len(b_txt) + 3
    o_q = o_c + len(c_txt) + 3
    men, st = [], {"secA": [], "secB": [], "secC": []}

    def add(key, kind, sym, cs, ce):
        assert text[cs:ce] in ("[%s%02X]" % (kind, sym), "{%d}" % sym, "%d" % sym), (text[cs:ce], kind, sym)
        men.append((key, kind, sym, cs, ce))
        return len(men) - 1

    ma = list(_MK.finditer(head))
    assert len(ma) % 2 == 0
    for m1, m2 in zip(ma[0::2], ma[1::2]):
        assert m1.group(1) == "R" and m2.group(1) == "X"
        r, x = int(m1.group(2), 16), int(m2.group(2), 16)
        st["secA"].append((add(("A", "R", r), "R", r, m1.start(), m1.end()),
                           add(("A", "X", x), "X", x, m2.start(), m2.end())))
    mb = list(_MK.finditer(b_txt))
    for m1, m2 in zip(mb[0::2], mb[1::2]):
        assert m1.group(1) == "X" and m2.group(1) == "Y"
        x, y = int(m1.group(2), 16), int(m2.group(2), 16)
        st["secB"].append((add(("B", "X", x), "X", x, o_b + m1.start(), o_b + m1.end()),
                           add(("B", "Y", y), "Y", y, o_b + m2.start(), o_b + m2.end())))
    pc = re.compile(r"\[Y([0-9A-F]{2})\] \{(\d+)\}")
    for m in pc.finditer(c_txt):
        y, f = int(m.group(1), 16), int(m.group(2))
        st["secC"].append((add(("C", "Y", y), "Y", y, o_c + m.start(), o_c + m.start() + 5),
                           add(("C", "F", f), "F", f, o_c + m.start(2), o_c + m.end(2))))
    mq = re.fullmatch(r"\[R([0-9A-F]{2})\] \{(\d+)\} \?", q_txt)
    qr, cand = int(mq.group(1), 16), int(mq.group(2))
    st["q"] = add(("Q", "R", qr), "R", qr, o_q, o_q + 5)
    st["cand"] = add(("Q", "F", cand), "F", cand, o_q + mq.start(2), o_q + mq.end(2))
    assert len(st["secA"]) == len(st["secB"]) == len(st["secC"]) == 16
    return {"text": text, "label": int(label), "mentions": men, **st}


def build_A(split, view2=False):
    M = _mods()
    cfg = BC.chain_cfg(M)
    n, off = {"train": (N_SPLIT["A"][0], 42), "dev": (N_SPLIT["A"][1], BC.DEV_OFFSET),
              "test": (N_SPLIT["A"][2], 123)}[split]
    out = []
    for i in range(n):
        text, label = BC.gen_chain(i, off, cfg, random.Random(BC.VIEW2_OFFSET + i) if view2 else None)
        out.append(_a_struct(text, label))
    return out


# ------------------------------------------------------------------ arena B (b27_common.make_b_arena, text kept)

def _b_struct(text, label, qr, cand):
    men, ctx = [], []
    pat = re.compile(r"\[R([0-9A-F]{2})\]\{(\d+)\}")
    ms = list(pat.finditer(text))
    for m in ms[:-1]:
        r, f = int(m.group(1), 16), int(m.group(2))
        men.append((("r", r), "R", r, m.start(1), m.end(1)))
        men.append((("f", r), "F", f, m.start(2), m.end(2)))
        ctx.append((len(men) - 2, len(men) - 1))
    mq = ms[-1]
    assert text[mq.end():] == " ?" and text[:mq.start()].endswith(" Q ")
    assert int(mq.group(1), 16) == qr and int(mq.group(2)) == cand
    men.append((("q",), "R", qr, mq.start(1), mq.end(1)))
    men.append((("cand",), "F", cand, mq.start(2), mq.end(2)))
    assert len(ctx) == 64
    return {"text": text, "label": int(label), "mentions": men, "ctx": ctx, "q": len(men) - 2, "cand": len(men) - 1}


def build_B(split, view2=False):
    M = _mods()
    SRB = M["systematic_role_binding_dataset"]
    cfg = SRB.SystematicConfig()
    n, offset, held = {"train": (N_SPLIT["B"][0], 42, False), "dev": (N_SPLIT["B"][1], BC.DEV_OFFSET, True),
                       "test": (N_SPLIT["B"][2], 123, True)}[split]
    ds = SRB.SystematicRoleBindingDataset(None, n, "eval" if held else "train", cfg)
    out = []
    for i in range(n):                                   # line by line b27_common.make_b_arena
        rng = random.Random(1000003 * i + offset)
        qr = rng.randrange(cfg.num_roles)
        tf = rng.choice(ds.train_allowed[qr] if not held else ds.eval_heldout[qr])
        r2f = ds._sample_context(rng, qr, tf)
        r2f[qr] = tf
        label = 1 if rng.random() < cfg.p_positive else 0
        if label == 1:
            cand = tf
        else:
            wr = rng.choice([r for r in range(cfg.num_roles) if r != qr])
            cand = r2f[wr]
            if cand == tf:
                cand = rng.choice([f for f in range(cfg.num_fillers) if f != tf])
        if view2:
            items = list(r2f.items()); random.Random(BC.VIEW2_OFFSET + i).shuffle(items)
            text = " ".join([SRB.make_role_token(r) + SRB.make_filler_token(f) for r, f in items]) + \
                " Q " + SRB.make_role_token(qr) + SRB.make_filler_token(cand) + " ?"
        else:
            text = ds._render_example(rng, r2f, qr, cand)
        s = _b_struct(text, label, qr, cand)
        s["true_f"] = tf
        out.append(s)
    return out


# ------------------------------------------------------------------ arena C (v13.Arena, text kept)

def _c_struct(text, label, q, cand, V):
    men, lv = [], [[] for _ in range(V.HOPS)]
    for m in V.PAT.finditer(text):
        L = V.LVL.index(m.group(1))
        if L >= V.HOPS:
            continue
        a, b = int(m.group(2), 16), int(m.group(3))
        men.append(((L, a, "r"), "R", a, m.start(2), m.end(2)))
        men.append(((L, a, "f"), "F", b, m.start(3), m.end(3)))
        lv[L].append((len(men) - 2, len(men) - 1))
    qm = V.QPAT.search(text)
    assert int(qm.group(1), 16) == q and int(qm.group(2)) == cand
    # the query sits mid-sequence: its mentions are appended after the context (index order is not text order)
    men.append((("q",), "R", q, qm.start(1), qm.end(1)))
    men.append((("cand",), "F", cand, qm.start(2), qm.end(2)))
    assert all(len(l) == V.N_CTX for l in lv)
    return {"text": text, "label": int(label), "mentions": men, "lv": lv, "q": len(men) - 2, "cand": len(men) - 1}


def build_C(split, view2=False):
    M = _mods()
    V = M["v13"]
    n, seed = {"train": (N_SPLIT["C"][0], 42), "dev": (N_SPLIT["C"][1], BC.DEV_SEED_C),
               "test": (N_SPLIT["C"][2], 4242)}[split]
    rng = random.Random(seed)
    out = []
    for i in range(n):                                   # line by line v13.Arena.__init__
        chain = [rng.randrange(V.N_SYM) for _ in range(V.HOPS + 1)]
        levels, toks = [], []
        for L in range(V.HOPS):
            pairs, seen = [(chain[L], chain[L + 1])], {chain[L]}
            while len(pairs) < V.N_CTX:
                a = rng.randrange(V.N_SYM)
                if a in seen:
                    continue
                seen.add(a); pairs.append((a, rng.randrange(V.N_SYM)))
            rng.shuffle(pairs); levels.append(pairs)
        for L, pairs in enumerate(levels):
            for a, b in pairs:
                toks.append("[%s%s]{%s}" % (V.LVL[L], V.h2(a), b))
        label = 1 if rng.random() < 0.5 else 0
        cand = chain[-1] if label == 1 else rng.choice([s for s in range(V.N_SYM) if s != chain[-1]])
        q = "Q [R%s] {%d} ?" % (V.h2(chain[0]), cand)
        text = (" ".join(toks) + " " + q) if V.Q_AT_END else \
               (" ".join(toks[:len(toks) // 2]) + " " + q + " " + " ".join(toks[len(toks) // 2:]))
        if view2:                                        # b27_common.make_c_view2: pairs reshuffled per level
            r2 = random.Random(BC.VIEW2_OFFSET + i)
            t2 = []
            for L in range(V.HOPS):
                pairs = list(levels[L])
                # make_c_view2 shuffles the pairs in their TEXT order (the row's ctx order), i.e. levels[L]
                r2.shuffle(pairs)
                t2 += ["[%s%s]{%s}" % (V.LVL[L], V.h2(a), b) for a, b in pairs]
            text = " ".join(t2[:len(t2) // 2]) + " " + q + " " + " ".join(t2[len(t2) // 2:])
        s = _c_struct(text, label, chain[0], cand, V)
        s["chain"] = chain
        out.append(s)
    return out


def build(arena, split, view2=False):
    return {"A": build_A, "B": build_B, "C": build_C}[arena](split, view2)


# ------------------------------------------------------------------ gold answers (the dictionary arm)

def dict_answer(arena, s):
    """Exact symbols + a dictionary: follow the gold pairs from the query; returns (predicted label, answer)."""
    sym = [m[2] for m in s["mentions"]]
    if arena == "A":
        d1 = {sym[r]: sym[x] for r, x in s["secA"]}
        d2 = {sym[x]: sym[y] for x, y in s["secB"]}
        d3 = {sym[y]: sym[f] for y, f in s["secC"]}
        ans = d3[d2[d1[sym[s["q"]]]]]
    elif arena == "B":
        ans = {sym[r]: sym[f] for r, f in s["ctx"]}[sym[s["q"]]]
    else:
        k = sym[s["q"]]
        for L in range(len(s["lv"])):
            k = {sym[r]: sym[f] for r, f in s["lv"][L]}[k]
        ans = k
    return int(ans == sym[s["cand"]]), ans


# ------------------------------------------------------------------ tokenizer side

def token_span(offsets, cs, ce):
    """v13.token_span / v11.token_span: the token range overlapping [cs, ce) (zero-length tokens skipped)."""
    lo = hi = None
    for i, (x, y) in enumerate(offsets):
        if y <= x:
            continue
        if x < ce and y > cs:
            lo = i if lo is None else lo
            hi = i + 1
    return (lo, hi) if lo is not None else None


def tokenize(tok, s, max_len=None, pad=False):
    """Token ids, attention mask and the token span of every mention. max_len/pad reproduce the published rows."""
    kw = dict(return_offsets_mapping=True)
    if pad:
        kw.update(truncation=True, max_length=max_len, padding="max_length")
    enc = tok(s["text"], **kw)
    offs = enc["offset_mapping"]
    spans = []
    for key, kind, sym, cs, ce in s["mentions"]:
        sp = token_span(offs, cs, ce)
        assert sp is not None, (key, s["text"][cs:ce])
        spans.append(sp)
    return enc["input_ids"], enc["attention_mask"], spans
