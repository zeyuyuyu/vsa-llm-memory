"""B47 verdict (prereg/B47_phi2_finetunes_hierboot_consistency_prereg.md). Written after the pre-registration (a1bf128)
and before any B47 test output is read. Every fine-tune test accuracy is recomputed from the saved margins /
generations with labels regenerated by b44_data; gates, bars, predictions and readings are applied as registered.

  python b47_verdict.py --root b47_out --out results/b47_verdict.txt
"""
import argparse, json, math, os, re, sys
from datetime import datetime
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
SEEDS = [42, 123, 456]
FLOOR = 0.472                       # B31 Phi-2 equalised probe, arena C (the published criterion's floor)
S_OBS = 0.30                        # largest mean same-symbol cosine among the arena-C label-free arms kept apart
B31_EXACT = {"perm": [1.0, 1.0, 1.0], "comm": [0.932, 0.932, 0.938]}
N_PHI2_C = [1.0, 1.0, 1.0]          # B31 Phi-2 naming head (perm, named), arena C, test per seed
L = []


def P(s=""):
    L.append(s); print(s)


def f3(x):
    return "%.3f" % x if x is not None and not (isinstance(x, float) and math.isnan(x)) else "-"


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def wilson(k, n, z=1.96):
    p = k / n; d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def test_meta():
    import b44_data as BD
    st = BD.split("std", "test", struct=False)
    y, candF = [], []
    for s in st:
        t = s["text"]
        F_vals = {int(b) for a, b in re.findall(r"\[F([0-9A-F]{2})\]\{(\d+)\}", t)}
        cand = int(re.search(r"Q \[R[0-9A-F]{2}\] \{(\d+)\} \?", t).group(1))
        y.append(BD.dict_answer(t)["label"]); candF.append(int(cand in F_vals))
    return np.array(y), np.array(candF), [s["text"] for s in st]


def parse_scratch(g):
    import b44_lora as BL
    lab = BL.parse_scratch(g)[0]
    return -1 if lab is None else lab


def ft_cell(root, task, variant, n, s, y):
    out = {"C": [], "acc": [], "logged": [], "info": [], "pred": []}
    for seed in SEEDS:
        base = os.path.join(root, "ft", "%s_%s_n%d_r%d_lr%s_s%d.json" % (task, variant, n, s["rank"], "%g" % s["lr"], seed))
        d, t = load(base), load(base + ".test.json")
        if d is None or t is None:
            return dict(out, missing=os.path.basename(base))
        if task == "scratch":
            pred = np.array([parse_scratch(g) for g in t["test"]["gens"]])
        else:
            pred = np.array([int(x > 0) for x in t["test"]["scores"]])
        c = (pred == y).astype(int)
        r = d["run"]
        out["C"].append(c); out["acc"].append(float(c.mean())); out["logged"].append(t["test"]["acc"]); out["pred"].append(pred)
        out["info"].append({"best_step": r["best_step"], "best_dev": r["best_dev"], "early_stop": r.get("early_stop"),
                            "train_sub_max": max(e["train_sub"]["acc"] for e in r["evals"]),
                            "dev_recheck": t["dev_recheck"]["acc"], "secs": r["secs"], "gpu": d.get("gpu"),
                            "free": {k: t["test"].get(k) for k in ("free_yesno_rate", "free_acc", "pos_rate", "unparsed",
                                                                  "bridge_acc", "bridge_hex_acc", "answer_sym_acc")
                                     if k in t["test"]}})
    out["mean"] = float(np.mean(out["acc"]))
    out["ok"] = all(abs(a - b) < 1e-6 for a, b in zip(out["acc"], out["logged"]))  # logged values are float32
    return out


def margin_reading(N, B):
    m = [a - b for a, b in zip(N, B)]
    M = float(np.mean(N) - np.mean(B))
    if M >= 0.10 and all(x >= 0.10 for x in m):
        return M, m, "STANDS"
    if M <= 0.03:
        return M, m, "CLOSED"
    return M, m, "NARROWED"


def hb_lookup(HB, mid):
    for m in (HB or {}).get("margins", []):
        if m["id"] == mid:
            return m
    return None


def ci_txt(m):
    if not m:
        return "(hierarchical intervals: not computed)"
    c = m["ci"]
    return "H-nest [%+.3f, %+.3f], H-cross [%+.3f, %+.3f], t-seed %s" % (
        *c["hnest"], *c["hcross"], "[%+.3f, %+.3f]" % tuple(c["tseed"]) if c.get("tseed") else "-")


def interp(xs, ys, x0):
    """linear interpolation of ys at x0 along xs (xs need not be sorted)."""
    o = np.argsort(xs); xs = np.asarray(xs)[o]; ys = np.asarray(ys)[o]
    if x0 <= xs[0]:
        return float(ys[0])
    if x0 >= xs[-1]:
        return float(ys[-1])
    return float(np.interp(x0, xs, ys))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.join(HERE, "b47_out"))
    ap.add_argument("--out", default=os.path.join(HERE, "results", "b47_verdict.txt"))
    ap.add_argument("--scores", default=os.path.join(HERE, "b47_out", "b47_scores.json"))
    a = ap.parse_args()
    R = a.root
    S = {}
    P("# B47 verdict (prereg/B47_phi2_finetunes_hierboot_consistency_prereg.md). Generated by b47_verdict.py on %s UTC."
      % datetime.utcnow().strftime("%Y-%m-%d %H:%M"))
    P("# Arena C (B31's test split, 500) unless stated; per seed 42/123/456 [Wilson 95%]; means with hierarchical")
    P("# seed-by-question intervals (b47_hierboot.json: H-nest primary, H-cross and t-seed checks).")

    # ---------------- gates
    P("\n## Gates")
    st = load(os.path.join(R, "selftest_tok.json")) or {}
    ok_tok = bool(st) and all(st.get("k32_%s_equals_b31" % s) for s in ("train", "dev", "test")) and \
        st.get("std_dev_ids_equal_k32") and st.get("std_test_ids_equal_k32") and \
        all(st.get("dict_equals_label_%s" % k) == st.get("n_%s" % k) for k in
            ("k32_train", "k32_dev", "k32_test", "std_train", "std_dev", "std_test"))
    P("  tokenisation self-test (k32 = B31 texts; std dev/test = k32; dictionary = label everywhere): %s" %
      ("PASS" if ok_tok else "FAIL / missing"))
    SW = {w: load(os.path.join(R, "sweep_%s.json" % w)) for w in ("consistency", "grid", "coherence")}
    g1 = None
    if SW["consistency"]:
        g1 = True
        for enc in ("perm", "comm"):
            c = [x for x in SW["consistency"]["cells"] if x["rho"] == 1.0 and x["structure"] == "mention" and x["enc"] == enc][0]
            accs = [r["acc"] for r in c["per_seed"]]
            ok = all(abs(u - v) < 1e-9 for u, v in zip(accs, B31_EXACT[enc]))
            g1 &= ok
            P("  G1  rho 1, c 0, %s: %s (B31 exact + VSA %s)  %s" % (enc, "/".join(f3(x) for x in accs),
                                                                   "/".join(f3(x) for x in B31_EXACT[enc]), "PASS" if ok else "FAIL"))
    g1b = None
    b44s = load(os.path.join(HERE, "results", "b44_xtalk_sweep.json"))
    if SW["coherence"] and b44s:
        g1b = True; worst = 0.0
        for row in b44s["curve"]:
            for enc in ("perm", "comm"):
                mine = [x for x in SW["coherence"]["cells"] if abs(x["c"] - row["c"]) < 1e-12 and x["enc"] == enc][0]
                d = max(abs(u["acc"] - v) for u, v in zip(mine["per_seed"], row["raw/%s" % enc]["acc"]))
                worst = max(worst, d); g1b &= d <= 0.002 + 1e-9
        P("  G1b coherence sweep (rho 1) in B47's code path vs B44's raw/perm and raw/comm, 14 levels x 3 seeds: largest "
          "per-seed difference %.4f  %s" % (worst, "PASS" if g1b else "FAIL"))
    S["gates"] = {"tok": ok_tok, "G1": g1, "G1b": g1b}

    # ---------------- (1) fine-tunes
    P("\n## (1) Phi-2 arena-C fine-tunes")
    sel = load(os.path.join(R, "select.json")) or {}
    y, candF, texts = test_meta()
    P("  dev selections (seed 42, train + dev only; B31 rule: fit = training subset >= 0.95):")
    for k in ("gen_k32_n800", "fullgen_k32_n800", "fullcls_k32_n800", "scratch_k32_n800", "gen_std_n8000",
              "fullgen_std_n8000"):
        s = sel.get(k)
        if not s:
            P("    %-18s not selected (runs missing)" % k); continue
        P("    %-18s -> rank %d lr %g (dev %.3f at step %s, training-subset max %.3f, fits %s)" % (
            k, s["rank"], s["lr"], s["dev"], s["best_step"], s["train_sub_max"], s["fit"]))
        P("        grid: " + "; ".join("r%d lr%g dev %.3f train %.3f%s" % (g["rank"], g["lr"], g["dev"], g["train_sub_max"],
                                                                          " (early stop %s)" % g["early_stop"] if g.get("early_stop") else "")
                                      for g in s["grid"]))
    CELLS = {}
    for task, variant, n, lab in (("gen", "k32", 800, "generative answer-token LoRA"),
                                  ("fullgen", "k32", 800, "full fine-tune, answer token"),
                                  ("fullcls", "k32", 800, "full fine-tune, B31 classifier read-out"),
                                  ("scratch", "k32", 800, "scratchpad LoRA (B44 code)"),
                                  ("gen", "std", 8000, "generative answer-token LoRA"),
                                  ("fullgen", "std", 8000, "full fine-tune, answer token")):
        s = sel.get("%s_%s_n%d" % (task, variant, n))
        if not s:
            P("  n=%-5d %-42s not run / not selected" % (n, lab)); continue
        c = ft_cell(R, task, variant, n, s, y)
        if c.get("missing"):
            P("  n=%-5d %-42s incomplete (%s)" % (n, lab, c["missing"])); continue
        CELLS[(task, n)] = c
        hb = load(os.path.join(R, "b47_hierboot.json"))
        acc_h = (hb or {}).get("accuracies", {}).get("b47|phi2|C|%s|n%d" % (task, n))
        P("  n=%-5d %-42s mean %.3f %s  seeds %s%s" % (
            n, lab, c["mean"], "[H-nest %.3f-%.3f]" % tuple(acc_h["hnest"]) if acc_h else "",
            ", ".join("%.3f [%.3f-%.3f]" % (x, *wilson(int(round(x * 500)), 500)) for x in c["acc"]),
            "" if c["ok"] else "  RECOMPUTED != LOGGED"))
        P("          dev-best step %s; dev %s (recheck %s); training-subset max %s; early stop %s" % (
            "/".join(str(i["best_step"]) for i in c["info"]), "/".join(f3(i["best_dev"]) for i in c["info"]),
            "/".join(f3(i["dev_recheck"]) for i in c["info"]), "/".join(f3(i["train_sub_max"]) for i in c["info"]),
            "/".join(str(i["early_stop"]) for i in c["info"])))
        P("          test extras: %s" % " | ".join(json.dumps(i["free"]) for i in c["info"]))
        diag = []
        for pr in c["pred"]:
            ok = pr == y
            diag.append("pos %.3f, neg cand-not-F %.3f, neg cand-F %.3f" % (
                ok[y == 1].mean(), ok[(y == 0) & (candF == 0)].mean(), ok[(y == 0) & (candF == 1)].mean()))
        P("          by label / candidate (shortcut 'yes iff cand is an F value' = 1/1/0, 0.798 overall): %s" % " || ".join(diag))
        S["cell|%s|n%d" % (task, n)] = {k: c[k] for k in ("acc", "mean", "ok")}
        S["cell|%s|n%d" % (task, n)]["info"] = c["info"]

    P("\n## (1) bars")
    for n in (800, 8000):
        prim = [CELLS[(t, n)] for t in ("gen", "fullgen") if (t, n) in CELLS]
        if len(prim) < 2:
            P("  n=%d: primary arms incomplete (%d of 2) -> bar not evaluable" % (n, len(prim)))
            S["F2|n%d" % n] = None
            if not prim:
                continue
        tb = max([t for t in ("gen", "fullgen") if (t, n) in CELLS], key=lambda t: CELLS[(t, n)]["mean"])
        B = CELLS[(tb, n)]
        Nacc, nlabel, ntag = N_PHI2_C, "B31 naming head (800)", "" if n == 800 else "800"
        if n == 8000 and os.path.exists(os.path.join(R, "name", "phi2_name_std_n8000.json")):
            import b47_boot as HBm
            n8 = HBm.mem(os.path.join(R, "name", "phi2_name_std_n8000.json"), "perm/named", y)
            Nacc, nlabel, ntag = n8["acc"], "Phi-2 naming head trained on the 8,000 (%s)" % "/".join(
                "%.3f" % x for x in n8["acc"]), "8000"
            S["N8000"] = {"acc": n8["acc"], "epoch": n8["epoch"], "ok": n8["recomputed_equals_logged"]}
        M, m, o = margin_reading(Nacc, B["acc"])
        hbm = hb_lookup(load(os.path.join(R, "b47_hierboot.json")), "b47|phi2|C|n%d|name%s-%s" % (n, ntag, tb))
        if len(prim) == 2:
            S["F2|n%d" % n] = {"vs": tb, "M": M, "m": m, "reading": o}
        P("  F2 n=%-5d %s %.3f vs %s %.3f: margin %+.3f (per seed %s) -> %s; %s" % (
            n, nlabel, float(np.mean(Nacc)), tb, B["mean"], M, "/".join("%+.3f" % x for x in m), o if len(prim) == 2 else o + " (incomplete)",
            ci_txt(hbm)))
        if n == 800:
            for t in ("gen", "fullgen", "fullcls"):
                if (t, 800) in CELLS:
                    fit = sel["%s_k32_n800" % t]["fit"]; anyfit = sel["%s_k32_n800" % t]["any_fit"]
                    P("  F1 %-8s n=800 selected configuration fits: %s (any grid configuration fits: %s; %d configurations)"
                      % (t, "FITS" if fit else "DOES NOT FIT", anyfit, len(sel["%s_k32_n800" % t]["grid"])))
                    S["F1|%s" % t] = {"fit": fit, "any_fit": anyfit}
            allc = {t: CELLS[(t, 800)] for t in ("gen", "fullgen", "fullcls", "scratch") if (t, 800) in CELLS}
            if allc:
                t2 = max(allc, key=lambda t: allc[t]["mean"])
                M2, m2, o2 = margin_reading(N_PHI2_C, allc[t2]["acc"])
                S["F2sec|n800"] = {"vs": t2, "M": M2, "m": m2, "reading": o2, "arms": sorted(allc)}
                P("  secondary n=800 vs the strongest of %s (%s %.3f): margin %+.3f (per seed %s) -> %s" % (
                    "/".join(sorted(allc)), t2, allc[t2]["mean"], M2, "/".join("%+.3f" % x for x in m2), o2))

    # ---------------- (2) hierarchical intervals
    HB = load(os.path.join(R, "b47_hierboot.json"))
    P("\n## (2) Hierarchical seed-by-question intervals (b47_out/b47_hierboot.json; 10,000 replicates)")
    if HB:
        P("  %-46s %8s  %-18s %-18s %-18s %-18s %s" % ("margin", "point", "H-nest", "H-cross", "t-seed", "instance-only", "flag"))
        for m in HB["margins"]:
            c = m["ci"]
            P("  %-46s %+8.3f  %-18s %-18s %-18s %-18s %s" % (
                m["id"], m["point"], "[%+.3f, %+.3f]" % tuple(c["hnest"]), "[%+.3f, %+.3f]" % tuple(c["hcross"]),
                "[%+.3f, %+.3f]" % tuple(c["tseed"]) if c.get("tseed") else "-",
                "[%+.3f, %+.3f]" % tuple(c["inst"]) if c.get("inst") else "-", m["flag"]))
        P("\n  recoveries R = (acc - F) / (N - F)")
        for r in HB["recoveries"]:
            if r["point"] is None:
                P("  %-46s undefined (gap %.3f < 0.10)" % (r["id"], r["gap"])); continue
            c = r["ci"]
            P("  %-46s %8.3f  [%.3f, %.3f]  [%.3f, %.3f]  %s" % (
                r["id"], r["point"], *c["hnest"], *c["hcross"], "[%.3f, %.3f]" % tuple(c["tseed"]) if c.get("tseed") else "-"))
        bad = [k for k, v in HB["accuracies"].items() if v["recomputed_equals_logged"] is False]
        P("  accuracies recomputed from saved outputs differing from the logged ones: %s" % (bad or "none"))
        for nt in HB.get("notes", []):
            P("  note: %s" % nt)

    # ---------------- (3) sweep
    P("\n## (3) Consistency sweep (B31 arena C, exact orthogonal codes, c = 0 unless stated; threshold on train)")
    CS = SW["consistency"]
    reading3 = None
    if CS:
        def rows(struct, enc):
            return sorted([x for x in CS["cells"] if x["structure"] == struct and x["enc"] == enc], key=lambda x: -x["rho"])
        P("  rho   same   diff  | mention/perm acc (seeds) dev | hop1 hop2 both | acc|chain right, wrong | comm  | form/perm")
        pm, cm, fm = rows("mention", "perm"), rows("mention", "comm"), rows("form", "perm")
        for x, xc, xf in zip(pm, cm, fm):
            ps = x["per_seed"]
            P("  %.2f  %.3f  %+.3f | %.3f (%s) %.3f | %.3f %.3f %.3f | %s, %s | %.3f | %.3f" % (
                x["rho"], x["geom_same_mean"], x["geom_different_mean"], x["acc_mean"],
                "/".join(f3(r["acc"]) for r in ps), x["dev_acc_mean"], x["hop1_mean"], x["hop2_mean"], x["both_mean"],
                f3(np.mean([r["acc_chain_right"] for r in ps if r["acc_chain_right"] is not None])),
                f3(np.mean([r["acc_chain_wrong"] for r in ps if r["acc_chain_wrong"] is not None])) if any(r["acc_chain_wrong"] is not None for r in ps) else "-",
                xc["acc_mean"], xf["acc_mean"]))
        same = [x["geom_same_mean"] for x in pm]; acc = [x["acc_mean"] for x in pm]
        A30 = interp(same, acc, S_OBS)
        reading3 = "SUFFICIENT" if A30 <= FLOOR + 0.10 else ("NOT SUFFICIENT" if A30 >= 0.90 else "PARTIAL")
        o = np.argsort(same)
        s_tol = next((same[i] for i in o if acc[i] >= FLOOR + 0.10), None)
        s_95 = next((same[i] for i in o if acc[i] >= 0.95), None)
        rho_tol = next((pm[i]["rho"] for i in o if acc[i] >= FLOOR + 0.10), None)
        rho_95 = next((pm[i]["rho"] for i in o if acc[i] >= 0.95), None)
        h1_30 = interp(same, [x["hop1_mean"] for x in pm], S_OBS)
        P("  A(s = %.2f) = %.3f (floor + 0.10 = %.3f) -> %s" % (S_OBS, A30, FLOOR + 0.10, reading3))
        P("  tolerance: smallest measured same-symbol cosine with accuracy >= %.3f: %s (rho %s); with >= 0.95: %s (rho %s)" % (
            FLOOR + 0.10, f3(s_tol), rho_tol, f3(s_95), rho_95))
        P("  hop-1 clean-up correctness at s = %.2f: %.3f (B42 label-free arms, measured: 0.032-0.184)" % (S_OBS, h1_30))
        S["sweep"] = {"A30": A30, "reading": reading3, "s_tol": s_tol, "rho_tol": rho_tol, "s_95": s_95, "rho_95": rho_95,
                      "hop1_30": h1_30,
                      "comm_below_perm_rho_ge_0.6": all(xc["acc_mean"] < x["acc_mean"] for x, xc in zip(pm, cm) if x["rho"] >= 0.6),
                      "form_ge_mention": all(xf["acc_mean"] >= x["acc_mean"] - 1e-12 for x, xf in zip(pm, fm)),
                      "perm_ge099_rho_ge085": all(x["acc_mean"] >= 0.99 for x in pm if x["rho"] >= 0.85 - 1e-9),
                      "perm_le572_rho_le045": all(x["acc_mean"] <= FLOOR + 0.10 for x in pm if x["rho"] <= 0.45 + 1e-9)}
    GR = SW["grid"]
    if GR and CS:
        P("\n  grid (perm, mention): accuracy by coherence c (rows) and consistency rho (columns); measured geometry in brackets")
        allrows = [x for x in CS["cells"] if x["structure"] == "mention" and x["enc"] == "perm"] + GR["cells"]
        for cc in (0.0, 0.1, 0.2, 0.3):
            rr = sorted([x for x in allrows if abs(x["c"] - cc) < 1e-9], key=lambda x: -x["rho"])
            P("  c %.1f: %s" % (cc, " ".join("%.2f:%.3f(%.2f/%.2f)" % (x["rho"], x["acc_mean"], x["geom_different_mean"],
                                                                       x["geom_same_mean"]) for x in rr)))
        arms = load(os.path.join(R, "observed_arms_C.json")) or []
        if arms:
            P("\n  label-free arms (arena C) placed at their measured geometry: nearest grid cell (Euclidean in different/same)")
            for arm in arms:
                d_, s_ = arm["different_mean"], arm["same_mean"]
                best = min(allrows, key=lambda x: (x["geom_different_mean"] - d_) ** 2 + (x["geom_same_mean"] - s_) ** 2)
                P("    %-44s geometry %.3f/%.3f, observed acc %.3f, hop1 %s | nearest cell c %.1f rho %.2f (%.3f/%.3f): "
                  "acc %.3f, hop1 %.3f" % (arm["label"], d_, s_, arm["acc_mean"], f3(arm.get("hop1_mean")), best["c"],
                                            best["rho"], best["geom_different_mean"], best["geom_same_mean"],
                                            best["acc_mean"], best["hop1_mean"]))
    # ---------------- exploratory controls (not registered bars)
    import glob as _g
    cf = sorted(_g.glob(os.path.join(R, "ctrl", "*.json")))
    if cf:
        P("\n## EXPLORATORY 1 / 2 (prereg/B47_exploratory1.md, B47_exploratory2.md): answer-token positive controls, train + dev")
        for f in cf:
            d = load(f); r = d["run"]
            P("  %-48s best dev %.3f; training subset %s; dev %s" % (
                os.path.basename(f), r["best_dev"], "/".join("%.3f" % e["train_sub"]["acc"] for e in r["evals"]),
                "/".join("%.3f" % e["dev"]["acc"] for e in r["evals"])))
        P("  majority baselines: candF 0.702 (dev), lastpar 0.544 (dev)")

    # ---------------- predictions
    P("\n## Predictions (registered)")

    def pr(name, val):
        P("  %-100s %s" % (name, {True: "HELD", False: "NOT HELD", None: "not evaluable"}[val]))
        S.setdefault("predictions", {})[name[:4].strip()] = val
    pr("P1  tokenisation self-test and gates G1 / G1b pass", (ok_tok and g1 and g1b) if (g1 is not None and g1b is not None) else None)
    sg = sel.get("gen_k32_n800")
    pr("P2  gen at 800 does not fit in any of its six configurations", (not sg["any_fit"]) if sg else None)
    sf, sc = sel.get("fullgen_k32_n800"), sel.get("fullcls_k32_n800")
    pr("P3  fullgen at 800 fits in at least one configuration; fullcls too", (sf["any_fit"] and sc["any_fit"]) if (sf and sc) else None)
