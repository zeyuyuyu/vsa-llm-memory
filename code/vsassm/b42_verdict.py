"""B42 verdict (prereg/B42_label_free_discrete_prereg.md). Written before any B42 test output of a registered run exists.

Every test accuracy is recomputed from the saved per-instance outputs (final cosine against the saved training
threshold at each seed's dev-selected epoch) and labels regenerated by b31_struct, and compared with the logged value.
References (floor F = B31 equalised probe, naming head N = B31 naming head perm/named, exact symbols, B31
binding-loss and InfoNCE maps) are read from B31's banked per-instance test outputs. Bars, predictions and readings
are applied as registered.

  python b42_verdict.py --root /path/to/work/b42/out --b31 /path/to/work/b31/out \
      --ledger /path/to/work/b42/logs/gpu_ledger.txt --out results/b42_verdict.txt --scores results/b42_scores.json
"""
