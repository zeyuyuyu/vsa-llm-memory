def P(s=""):
    L.append(s); print(s)


def f3(x):
    return "%.3f" % x if x is not None and x == x else "n/a"


def load(p):
    if os.path.exists(p):
        return json.load(open(p))
    if os.path.exists(p + ".gz"):
        return json.load(gzip.open(p + ".gz", "rt"))
    return None


def wilson(k, n, z=1.96):
    p = k / n; d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


IDX = {}


def boot_idx(n, B=10000, seed=0):
    if (n, seed) not in IDX:
        IDX[(n, seed)] = np.random.default_rng(seed).integers(0, n, size=(B, n))
    return IDX[(n, seed)]


def boot_means(C):
    C = np.asarray(C, float)
    idx = boot_idx(C.shape[1])
    return C[:, idx].mean(axis=2).mean(axis=0)               # (B,)


def ci(v):
    return float(np.percentile(v, 2.5)), float(np.percentile(v, 97.5))


def sel_epoch(run, reading):
    accs = [e["%s:dev" % reading]["acc"] for e in run["epochs"]]
    return max(range(len(accs)), key=lambda j: (accs[j], -j))


def memory_arm(path, reading, y):
    d = load(path)
    if d is None:
        return None
    out = {"acc": [], "C": [], "logged": [], "geom": [], "epoch": [], "final": [], "disc": [], "wins": [], "train": [],
           "dev": []}
    for run in d["runs"]:
        j = sel_epoch(run, reading)
        e = run["epochs"][j]["%s:test" % reading]
        pred = (np.array(e["scores"]) >= e["thr"]).astype(int)
        c = (pred == y).astype(int)
        out["C"].append(c); out["acc"].append(float(c.mean())); out["logged"].append(e["acc"])
        out["epoch"].append(run["epochs"][j]["epoch"]); out["train"].append(e["train_acc"])
        out["dev"].append(run["epochs"][j]["%s:dev" % reading]["acc"])
        out["geom"].append(e.get("geom")); out["disc"].append(e.get("discrete")); out["wins"].append(e.get("wins"))
        out["final"].append(run["epochs"][-1]["%s:test" % reading]["acc"])
    out["args"] = d.get("args")
    return summarise(out)


def probe_arm(path, y):
    d = load(path)
    if d is None:
        return None
    out = {"acc": [], "C": [], "logged": []}
    for r in d["runs"]:
        c = (((np.array(r["test_scores"]) > 0).astype(int)) == y).astype(int)
        out["C"].append(c); out["acc"].append(float(c.mean())); out["logged"].append(r["test_acc"])
    return summarise(out)


def summarise(r):
    C = np.array(r["C"])
    r["mean"] = float(C.mean(axis=1).mean())
    r["bm"] = boot_means(C)
    r["ci"] = ci(r["bm"])
    r["wilson"] = [wilson(int(c.sum()), C.shape[1]) for c in C]
    r["recomputed_equals_logged"] = all(abs(a - b) < 1e-9 for a, b in zip(r["acc"], r["logged"]))
    return r


def hop_rates(ar, st, wins):
    """Fraction of test instances whose clean-up winner is the gold symbol at hop 1 and at hop 2 (A, C)."""
    if wins is None or ar == "B":
        return None
    W = np.array(wins)
    h1, h2 = [], []
    for i, s in enumerate(st):
        sym = [m[2] for m in s["mentions"]]
        if ar == "C":
            g1, g2 = s["chain"][1], s["chain"][2]
        else:
            d1 = {sym[r]: sym[x] for r, x in s["secA"]}; d2 = {sym[x]: sym[y] for x, y in s["secB"]}
            g1 = d1[sym[s["q"]]]; g2 = d2[g1]
        h1.append(sym[W[i, 0]] == g1); h2.append(sym[W[i, 1]] == g2)
    return float(np.mean(h1)), float(np.mean(h2)), float(np.mean(np.array(h1) & np.array(h2)))


def bar(R, Rs):
    if R is None:
        return "no headroom"
    if R >= 0.90:
        return "MATCHES" + ("" if all(r >= 0.80 for r in Rs) else " (a seed below 0.80)")
    return "PARTIAL" if R >= 0.25 else "FAIL"


def ledger(path):
    if not os.path.exists(path):
        return [], 0.0, {}
    st, rows = {}, []
    for l in open(path):
        p = l.split()
        if len(p) != 4:
            continue
        name, gpu, kind, t = p
        t = datetime.strptime(t, "%Y-%m-%dT%H:%M:%SZ")
        if kind == "start":
            st[(name, gpu)] = t
        elif (name, gpu) in st:
            rows.append((name, gpu, (t - st.pop((name, gpu))).total_seconds() / 3600))
    return rows, sum(r[2] for r in rows), st


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="/path/to/work/b42/out")
    ap.add_argument("--b31", default="/path/to/work/b31/out")
    ap.add_argument("--ledger", default="/path/to/work/b42/logs/gpu_ledger.txt")
    ap.add_argument("--arenas", default="ABC")
    ap.add_argument("--out", default="results/b42_verdict.txt")
    ap.add_argument("--scores", default="results/b42_scores.json")
    a = ap.parse_args()
    R, R31 = a.root, a.b31
    P("# B42 verdict (prereg/B42_label_free_discrete_prereg.md): label-free discrete interfaces against the naming")
    P("# head, on B31's frozen states. Generated by b42_verdict.py on %s UTC." % datetime.utcnow().strftime("%Y-%m-%d %H:%M"))
    ST = {ar: S.build(ar, "test") for ar in a.arenas}
    Y = {ar: np.array([s["label"] for s in ST[ar]]) for ar in a.arenas}

    # ---------------- gates
    P("\n## Gates (dev split)")
    gates_ok = True
    for ar in a.arenas:
        for enc in ENCS:
            k = "%s_%s" % (enc, ar)
            d42, d31 = load(os.path.join(R, "g0", "%s_bind.json" % k)), None
            if d42:
                lr = d42["args"]["lr"]
                d31 = load(os.path.join(R31, "arms_tune", "%s_bind_lr%g.json" % (k, lr)))
            if d42 and d31:
                x = [e["%s:dev" % PRIMARY]["acc"] for e in d42["runs"][0]["epochs"]]
                z = [e["%s:dev" % PRIMARY]["acc"] for e in d31["runs"][0]["epochs"]]
                diff = max(abs(u - v) for u, v in zip(x, z))
                ok = diff <= 0.004 + 1e-9
                gates_ok &= ok
                P("  G0 %-8s binding-loss map through the B42 code path vs B31 tuning run (lr %g): max |dev diff| over 10 "
                  "epochs %.4f  %s" % (k, lr, diff, "PASS" if ok else "FAIL"))
            else:
                P("  G0 %-8s missing" % k)
            nm = load(os.path.join(R31, "arms_final", "%s_name.json" % k))
            ndev = max(e["%s:dev" % PRIMARY]["acc"] for e in nm["runs"][0]["epochs"]) if nm else None
            for fam in ("gumbel", "st"):
                g1 = load(os.path.join(R, "g1", "%s_%s_g1.json" % (k, fam)))
                if g1 and ndev is not None:
                    gd = max(e["%s:dev" % PRIMARY]["acc"] for e in g1["runs"][0]["epochs"])
                    ok = gd >= ndev - 0.02
                    P("  G1 %-8s %-6s code path + identity loss (labelled control): best dev %.3f vs naming head %.3f  %s"
                      % (k, fam, gd, ndev, "PASS" if ok else "FAIL"))
                    gates_ok &= ok
    gp = {e: load(os.path.join(R, "gradpath_%s.json" % e)) for e in ENCS}
    for e, g in gp.items():
        if g:
            for kk, v in g.items():
                P("  gradient path %s %-7s %s" % (e, kk, ", ".join("%s %.2f" % (s, x) for s, x in v.items())))

    # ---------------- selections
    sel = load(os.path.join(R, "select.json")) or {}
    P("\n## Dev selections (seed 42, train + dev only; best-epoch dev accuracy, perm/named)")
    for fam in FAMS:
        for k, v in sorted(sel.get(fam, {}).items()):
            P("  %-7s %-8s %s dev %.3f (epoch %d) of %d configurations" % (fam, k, json.dumps(v["cfg"]), v["dev"],
                                                                          v["epoch"], len(sel["grids"][fam][k])))
        for k, rows in sorted(sel.get("grids", {}).get(fam, {}).items()):
            P("    grid %s %s: %s" % (fam, k, "; ".join("%s %.3f" % (",".join("%s=%s" % (kk, vv) for kk, vv in sorted(r["cfg"].items())
                                                                              if kk != "lr" or fam != "cw"), r["dev"]) for r in rows)))

    # ---------------- results
    RES = {}
    for ar in a.arenas:
        y = Y[ar]
        r = memory_arm(os.path.join(R31, "arms_final", "X_%s_exact.json" % ar), "perm/named", y)
        if r:
            RES[("X", ar, "r_exact")] = r
        for enc in ENCS:
            k = "%s_%s" % (enc, ar)
            for key, fn, rd in (("r_name", "%s_name.json" % k, PRIMARY), ("r_bind", "%s_bind.json" % k, PRIMARY),
                                ("r_nce", "%s_nce.json" % k, PRIMARY)):
                r = memory_arm(os.path.join(R31, "arms_final", fn), rd, y)
                if r:
                    RES[(enc, ar, key)] = r
            r = probe_arm(os.path.join(R31, "probe_final", "%s.json" % k), y)
            if r:
                RES[(enc, ar, "r_probe")] = r
            for fam in FAMS:
                r = memory_arm(os.path.join(R, "final", "%s_%s.json" % (k, fam)), PRIMARY, y)
                if r:
                    RES[(enc, ar, fam)] = r
            for rd, key in ((PRIMARY, "bind"), (PRIMARY + "+pc", "bind+pc"), (PRIMARY + "+pz", "bind+pz")):
                r = memory_arm(os.path.join(R, "final", "%s_bind.json" % k), rd, y)
                if r:
                    RES[(enc, ar, key)] = r
            for cl in ("hard", "st"):
                r = memory_arm(os.path.join(R, "final", "%s_dkvbor_%s.json" % (k, cl)), PRIMARY, y)
                if r:
                    RES[(enc, ar, "dkvbor_" + cl)] = r

    def get(enc, ar, k):
        return RES.get((enc, ar, k))

    P("\n## Results: test accuracy per seed (42/123/456) [Wilson 95%], mean [bootstrap 95%]; recovery R = (mean - F) /")
    P("## (N - F), F = B31 equalised probe, N = B31 naming head (perm, named); trained arms at each seed's dev-selected epoch")
    BAR = {}
    for ar in a.arenas:
        P("\n  arena %s (n = %d)" % (ar, len(Y[ar])))
        ex = get("X", ar, "r_exact")
        if ex:
            P("    %-9s %-56s mean %s" % ("no enc.", LBL["r_exact"], f3(ex["mean"])))
        for enc in ENCS:
            Fr, Nr = get(enc, ar, "r_probe"), get(enc, ar, "r_name")
            if not (Fr and Nr):
                continue
            gap = Nr["mean"] - Fr["mean"]
            P("    %s: floor F %.3f, naming head N %.3f, gap %.3f%s" % (ENCN[enc], Fr["mean"], Nr["mean"], gap,
                                                                   "" if gap >= 0.10 else " (< 0.10: recovery undefined)"))
            for key in ["r_name", "r_probe", "r_bind", "r_nce"] + LF + ["bind", "dkvbor_hard", "dkvbor_st"]:
                r = get(enc, ar, key)
                if r is None:
                    continue
                line = "    %-9s %-56s mean %s [%s-%s]  seeds %s" % (
                    ENCN[enc], LBL[key], f3(r["mean"]), f3(r["ci"][0]), f3(r["ci"][1]),
                    ", ".join("%s [%s-%s]" % (f3(x), f3(w[0]), f3(w[1])) for x, w in zip(r["acc"], r["wilson"])))
                if not r["recomputed_equals_logged"]:
                    line += "  RECOMPUTED != LOGGED"
                P(line)
                extra = []
                if gap >= 0.10 and key not in ("r_name", "r_probe"):
                    Rb = (r["bm"] - Fr["bm"]) / (Nr["bm"] - Fr["bm"])
                    Rm = (r["mean"] - Fr["mean"]) / gap
                    Rs = [(x - Fr["mean"]) / gap for x in r["acc"]]
                    lo, hi = ci(Rb)
                    b_ = bar(Rm, Rs)
                    if key in LF:
                        BAR[(enc, ar, key)] = (b_, Rm, (lo, hi), Rs)
                    extra.append("recovery %.3f [%.3f, %.3f] (seeds %s) -> %s" % (Rm, lo, hi, "/".join(
                        "%.2f" % x for x in Rs), b_ if key in LF else "(reference)"))
                elif key in LF:
                    BAR[(enc, ar, key)] = ("no headroom", None, None, None)
                    extra.append("vs floor %+.3f, vs naming head %+.3f (no headroom)" % (r["mean"] - Fr["mean"],
                                                                                        r["mean"] - Nr["mean"]))
                if r.get("geom") and r["geom"][0]:
                    extra.append("cross-talk different/same " + ", ".join(
                        "%s/%s" % (f3(g["different"]), f3(g["same"])) if g else "-" for g in r["geom"]))
                if r.get("disc") and r["disc"][0]:
                    ds = r["disc"]
                    extra.append("mention consistency %s, code purity %s, codes used %s%s" % (
                        "/".join(f3(x["consistency"]) for x in ds), "/".join(f3(x["purity"]) for x in ds),
                        "/".join(str(x["codes_used"]) for x in ds),
                        ("; hex/decimal alias rate " + "/".join(f3(x.get("alias_rate")) for x in ds)) if ar == "C" else ""))
                if r.get("wins") and r["wins"][0] is not None and ar in "AC":
                    hr = [hop_rates(ar, ST[ar], w) for w in r["wins"]]
                    extra.append("clean-up correct at hop 1 / hop 2 / both: " + ", ".join(
                        "%s/%s/%s" % (f3(h[0]), f3(h[1]), f3(h[2])) for h in hr if h))
                if r.get("epoch"):
                    extra.append("dev-selected epoch %s; dev %s; train %s; final-epoch test %s" % (
                        "/".join(str(x) for x in r["epoch"]), "/".join(f3(x) for x in r["dev"]),
                        "/".join(f3(x) for x in r["train"]), "/".join(f3(x) for x in r["final"])))
                for x in extra:
                    P("              %s" % x)

    # ---------------- the registered bar
    P("\n## Primary bar: a label-free arm MATCHES if its mean recovery in arena C is >= 0.90 on BOTH encoders")
    matches = []
    for key in LF:
        rows = [BAR.get((enc, "C", key)) for enc in ENCS]
        if any(r is None for r in rows):
            P("  %-56s incomplete" % LBL[key]); continue
        both = all(r[0].startswith("MATCHES") for r in rows)
        if both:
            matches.append(key)
        P("  %-56s Phi-2 %s (R %.3f), Qwen3-8B %s (R %.3f) -> %s" % (
            LBL[key], rows[0][0], rows[0][1], rows[1][0], rows[1][1], "MATCHES" if both else "DOES NOT MATCH"))
    P("  ANSWER: a label-free interface reaches the naming head in arena C on both encoders: %s%s" % (
        "YES (" + ", ".join(matches) + ")" if matches else "NO", "" if all(
            BAR.get((e, "C", k)) for e in ENCS for k in LF) else " [incomplete]"))
    P("\n## Secondary: arenas A and B")
    for ar in [x for x in a.arenas if x != "C"]:
        for key in LF:
            rows = [BAR.get((enc, ar, key)) for enc in ENCS]
            P("  arena %s %-56s %s" % (ar, LBL[key], "; ".join(
                "%s %s%s" % (ENCN[e], r[0], " (R %.3f)" % r[1] if r and r[1] is not None else "") if r else "%s n/a" % ENCN[e]
                for e, r in zip(ENCS, rows))))

    # ---------------- second scorer
    P("\n## Second scorer (b42_indep.py: numpy float64, its own regex parse of the raw text, codes rebuilt from the saved")
    P("## assignments and codebooks, labels from the dictionary walk)")
    ind = load(os.path.join(R, "indep42.json"))
    agree = []
    if ind:
        for kk, v in sorted(ind.items()):
            P("  %-28s %s" % (kk, ", ".join("%s %s" % (x, f3(y) if isinstance(y, float) else y) for x, y in v.items())))
            if "agreement" in v:
                agree.append(v["agreement"])
    P("  every accuracy above recomputed from saved outputs equals the logged value: %s" % all(
        r["recomputed_equals_logged"] for r in RES.values()))

    # ---------------- predictions
    P("\n## Predictions (registered)")
    PRED = []

    def pr(name, cond):
        PRED.append((name, cond))
        P("  %-108s %s" % (name, "HELD" if cond else ("NOT HELD" if cond is not None else "n/a")))

    def mean_(enc, ar, k):
        r = get(enc, ar, k); return r["mean"] if r else None

    pr("P1 gates G0 and G1 pass", gates_ok)
    pr("P2 no label-free family MATCHES in arena C on both encoders", not matches if all(
        BAR.get((e, "C", k)) for e in ENCS for k in LF) else None)
    pr("P3 no label-free family MATCHES in arena C on either encoder", all(
        not BAR[(e, "C", k)][0].startswith("MATCHES") for e in ENCS for k in LF if (e, "C", k) in BAR))
    pr("P4 every label-free family's arena-C recovery < 0.25 (FAIL) on both encoders, except possibly one PARTIAL",
       sum(1 for e in ENCS for k in LF if (e, "C", k) in BAR and BAR[(e, "C", k)][1] is not None and
           BAR[(e, "C", k)][1] >= 0.25) <= 1)
    disc_alias = [d.get("alias_rate") for e in ENCS for k in ("vq", "dkvb", "gumbel", "st")
                  for d in ((get(e, "C", k) or {}).get("disc") or []) if d]
    pr("P5 discrete families in C: hex-role / decimal-filler alias rate <= 0.20 in every seed",
       all(x is not None and x <= 0.20 for x in disc_alias) if disc_alias else None)
    cwg = [g for e in ENCS for g in ((get(e, "C", "cw") or {}).get("geom") or []) if g]
    pr("P6 trained centred/whitened map in C: different-symbol cosine <= 0.25 and same-symbol <= 0.60 in every seed",
       all(g["different"] <= 0.25 and (g["same"] or 0) <= 0.60 for g in cwg) if cwg else None)
    pc = [(mean_(e, "C", "bind+pc"), mean_(e, "C", "bind")) for e in ENCS]
    pr("P7 post-hoc centring of the binding-loss map in C changes its accuracy by at most 0.03 on each encoder",
       all(x is not None and z is not None and abs(x - z) <= 0.03 for x, z in pc))
    pr("P8 surface-form oracle keys in C (diagnostic): st clean-up - hard clean-up >= +0.10 and hard <= 0.60, both encoders",
       all((mean_(e, "C", "dkvbor_st") or 0) - (mean_(e, "C", "dkvbor_hard") or 1) >= 0.10 and
           (mean_(e, "C", "dkvbor_hard") or 1) <= 0.60 for e in ENCS)
       if all(get(e, "C", "dkvbor_st") and get(e, "C", "dkvbor_hard") for e in ENCS) else None)
    if "A" in a.arenas:
        pr("P9 arena A, Phi-2: the best label-free family is PARTIAL (0.25 <= R < 0.90)",
           any(0.25 <= (BAR.get(("phi2", "A", k), (0, None))[1] or 0) < 0.90 for k in LF) and
           not any((BAR.get(("phi2", "A", k), (0, None))[1] or 0) >= 0.90 for k in LF))
    if "B" in a.arenas:
        pr("P10 arena B: every label-free family within 0.03 of the floor or above it, on both encoders",
           all((mean_(e, "B", k) or 0) >= (mean_(e, "B", "r_probe") or 1) - 0.03 for e in ENCS for k in FAMS))
    pr("P11 the second scorer agrees with the main runs on >= 0.99 of instances in every discrete cell",
       (min(agree) >= 0.99) if agree else None)

    # ---------------- compute
    P("\n## Compute (GPU occupancy per B42 worker, A800 80 GB; logs/gpu_ledger.txt)")
    rows, tot, open_ = ledger(a.ledger)
    for name, gpu, h_ in rows:
        P("  %-14s %s %.2f h" % (name, gpu, h_))
    if open_:
        P("  still open: %s" % ", ".join("%s %s" % k for k in open_))
    P("  total %.2f GPU-hours (cap 40)" % tot)
    pr("P12 total GPU-hours <= 10", tot <= 10)

    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    open(a.out, "w").write("\n".join(L) + "\n")
    js = {"%s|%s|%s" % k: {kk: v[kk] for kk in ("acc", "mean", "ci") if kk in v} for k, v in RES.items()}
    js["bar"] = {"%s|%s|%s" % k: v for k, v in BAR.items()}
    js["predictions"] = PRED
    json.dump(js, open(a.scores, "w"), indent=1)


if __name__ == "__main__":
    main()
