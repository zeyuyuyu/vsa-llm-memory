"""B48 verdict (prereg/B48_one_form_and_alias_naming_prereg.md). Written before any B48 test output exists.

Part A: every C1 test accuracy is recomputed from the saved per-instance scores and thresholds (each seed's dev-selected
epoch) against labels regenerated by b48_struct, and compared with the logged value; references F (probe) and N (naming
head) are the C1 runs on the same encoder; recovery, bar and answer as registered. Part B: accuracies recomputed from
the saved scores of b48_alias.py score; naming accuracy per mention type; recovery against hash and oracle; bars.

  python b48_verdict.py --root <b48>/out --indepA <b48>/out/indepA.json --indepB <b48>/out/indepB.json \
      --gpuh "<text>" --out results/b48_verdict.txt --scores results/b48_scores.json
"""
import argparse, json, math, os, sys
from datetime import datetime

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import b48_struct as S48                                                    # noqa: E402
from b42_verdict import (load, wilson, boot_means, boot_idx, ci, memory_arm, probe_arm, hop_rates)  # noqa: E402
from b42_queues import FAMS                                                 # noqa: E402
from b48_queues import ENCS, BINDLR                                         # noqa: E402

PRIMARY = "perm/named"
ENCN = {"phi2": "Phi-2", "qwen8": "Qwen3-8B"}
LF = FAMS + ["bind+pc", "bind+pz"]
LBL = {"vq": "VQ bottleneck (commitment, EMA, dead-code restart)", "dkvb": "discrete key-value bottleneck",
       "gumbel": "Gumbel-softmax over the fixed codebook", "st": "straight-through arg-max over the fixed codebook",
       "cw": "binding-loss map, centred / whitened (trained)", "bind": "binding-loss map (B31 form)",
       "bind+pc": "binding-loss map, post-hoc centring", "bind+pz": "binding-loss map, post-hoc ZCA whitening",
       "name": "naming head + VSA (perm, named)", "probe": "equalised probe (floor)", "exact": "exact symbols + VSA (perm)"}
L = []


def P(s=""):
    L.append(s); print(s)


def f3(x):
    return "%.3f" % x if x is not None and x == x else "n/a"


def rec_ci(r, F_, N_):
    """Recovery of an arm against floor and naming head (paired bootstrap over test instances)."""
    if N_ is None or F_ is None or N_["mean"] - F_["mean"] < 0.10:
        return None, None, None
    R = (r["mean"] - F_["mean"]) / (N_["mean"] - F_["mean"])
    bs = (r["bm"] - F_["bm"]) / np.where(np.abs(N_["bm"] - F_["bm"]) < 1e-9, np.nan, N_["bm"] - F_["bm"])
    Rs = [(x - F_["mean"]) / (N_["mean"] - F_["mean"]) for x in r["acc"]]
    return R, (float(np.nanpercentile(bs, 2.5)), float(np.nanpercentile(bs, 97.5))), Rs


def bar(R, Rs):
    if R is None:
        return "no headroom"
    if R >= 0.90:
        return "MATCHES" + ("" if all(x >= 0.80 for x in Rs) else " (a seed below 0.80)")
    return "PARTIAL" if R >= 0.25 else "FAIL"


def held(ok):
    return "HELD" if ok else "NOT HELD"


# ====================================================================== part A

def part_a(a, SC, PRED):
    R = a.root
    st = S48.build_C1("test")
    y = np.array([s["label"] for s in st])
    P("\n# PART A: arena C1 (one surface form per symbol), test n = %d" % len(y))
    P("\n## Gates (dev)")
    gates = {}
    nmdev = {}
    for enc in ENCS:
        k = "%s_C1" % enc
        d31 = load(os.path.join(R, "g0", "%s_bind_b31.json" % k))
        d42 = load(os.path.join(R, "bindtune", "%s_bind_lr%g.json" % (k, BINDLR[enc])))
        if d31 and d42:
            x = [e["%s:dev" % PRIMARY]["acc"] for e in d31["runs"][0]["epochs"]]
            z = [e["%s:dev" % PRIMARY]["acc"] for e in d42["runs"][0]["epochs"]]
            diff = max(abs(u - v) for u, v in zip(x, z))
            gates["G0_" + enc] = diff <= 0.002 + 1e-9
            P("  G0 %-8s b42 bind vs b31 bind on C1 dev (lr %g): max |dev diff| over 10 epochs %.4f  %s"
              % (k, BINDLR[enc], diff, "PASS" if gates["G0_" + enc] else "FAIL"))
        else:
            P("  G0 %-8s missing" % k)
        nm = load(os.path.join(R, "nametune", "%s_name.json" % k))
        nmdev[enc] = max(e["%s:dev" % PRIMARY]["acc"] for e in nm["runs"][0]["epochs"]) if nm else None
        for fam in ("gumbel", "st"):
            g1 = load(os.path.join(R, "g1", "%s_%s_g1.json" % (k, fam)))
            if g1 and nmdev[enc] is not None:
                gd = max(e["%s:dev" % PRIMARY]["acc"] for e in g1["runs"][0]["epochs"])
                gates["G1_%s_%s" % (enc, fam)] = gd >= nmdev[enc] - 0.02
                P("  G1 %-8s %-6s + identity loss (labelled control): best dev %.3f vs C1 naming head %.3f  %s"
                  % (k, fam, gd, nmdev[enc], "PASS" if gates["G1_%s_%s" % (enc, fam)] else "FAIL"))
    sel = load(os.path.join(R, "select.json")) or {}
    P("\n## Dev selections (seed 42, train + dev; best-epoch dev accuracy, perm/named)")
    for fam in FAMS + ["bind"]:
        for k, v in sorted(sel.get(fam, {}).items()):
            P("  %-7s %-9s %s dev %.3f (epoch %d) of %d configurations" % (
                fam, k, json.dumps(v.get("cfg", {"lr": v.get("lr")})), v["dev"], v["epoch"],
                len(sel["grids"][fam][k])))
    for k, v in sorted(sel.get("probe", {}).items()):
        P("  probe   %-9s %s" % (k, json.dumps(v)))
    RES = {}
    r = memory_arm(os.path.join(R, "final", "X_C1_exact.json"), PRIMARY, y)
    if r:
        RES[("X", "exact")] = r
    for enc in ENCS:
        k = "%s_C1" % enc
        for key, fn, rd in (("name", "%s_name.json" % k, PRIMARY), ("bind", "%s_bind.json" % k, PRIMARY),
                            ("bind+pc", "%s_bind.json" % k, PRIMARY + "+pc"),
                            ("bind+pz", "%s_bind.json" % k, PRIMARY + "+pz")):
            r = memory_arm(os.path.join(R, "final", fn), rd, y)
            if r:
                RES[(enc, key)] = r
        r = probe_arm(os.path.join(R, "final", "%s_probe.json" % k), y)
        if r:
            RES[(enc, "probe")] = r
        for fam in FAMS:
            r = memory_arm(os.path.join(R, "final", "%s_%s.json" % (k, fam)), PRIMARY, y)
            if r:
                RES[(enc, fam)] = r
    P("\n## Results: test accuracy per seed (42/123/456) [Wilson 95%], mean [bootstrap 95%]; recovery R = (mean - F) /")
    P("## (N - F), F = C1 probe, N = C1 naming head, same encoder; labels from b48_struct; recomputed from saved scores")
    if ("X", "exact") in RES:
        r = RES[("X", "exact")]
        P("    no enc.   %-55s mean %s  seeds %s  (= string hashing of the written symbol in C1)" % (
            LBL["exact"], f3(r["mean"]), "/".join(f3(x) for x in r["acc"])))
    verdict = {}
    for enc in ENCS:
        F_, N_ = RES.get((enc, "probe")), RES.get((enc, "name"))
        P("\n  %s: floor F %s, naming head N %s, gap %s" % (ENCN[enc], f3(F_["mean"]) if F_ else "n/a",
                                                         f3(N_["mean"]) if N_ else "n/a",
                                                         f3(N_["mean"] - F_["mean"]) if F_ and N_ else "n/a"))
        for key in ["name", "probe", "bind"] + LF:
            r = RES.get((enc, key))
            if r is None:
                P("    %-8s  %-55s NOT RUN / missing" % (ENCN[enc], LBL[key])); continue
            P("    %-8s  %-55s mean %s [%s-%s]  seeds %s%s" % (
                ENCN[enc], LBL[key], f3(r["mean"]), f3(r["ci"][0]), f3(r["ci"][1]),
                ", ".join("%s [%s-%s]" % (f3(x), f3(w[0]), f3(w[1])) for x, w in zip(r["acc"], r["wilson"])),
                "" if r["recomputed_equals_logged"] else "  RECOMPUTED != LOGGED (logged %s)" % "/".join(f3(x) for x in r["logged"])))
            SC["A_%s_%s" % (enc, key)] = {"mean": r["mean"], "ci": r["ci"], "acc": r["acc"]}
            if key in LF + ["bind"]:
                Rm, Rci, Rs = rec_ci(r, F_, N_)
                b = bar(Rm, Rs) if key in LF else "(reference)"
                if key in LF:
                    verdict[(enc, key)] = (Rm, b)
                if Rm is not None:
                    P("              recovery %s [%s, %s] (seeds %s) -> %s" % (f3(Rm), f3(Rci[0]), f3(Rci[1]),
                                                                           "/".join("%.2f" % x for x in Rs), b))
                    SC["A_%s_%s" % (enc, key)]["recovery"] = [Rm, Rci]
            if r.get("geom") and r["geom"][0]:
                P("              cross-talk different/same %s" % ", ".join(
                    "%s/%s" % (f3(g["different"]), f3(g["same"])) for g in r["geom"] if g))
            if r.get("disc") and r["disc"][0]:
                P("              mention consistency %s, code purity %s, codes used %s" % (
                    "/".join(f3(d["consistency"]) for d in r["disc"]), "/".join(f3(d["purity"]) for d in r["disc"]),
                    "/".join(str(d["codes_used"]) for d in r["disc"])))
            if r.get("wins") and r["wins"][0] is not None:
                hr = [hop_rates("C", st, w) for w in r["wins"]]
                P("              clean-up correct at hop 1 / hop 2 / both: %s" % ", ".join(
                    "%s/%s/%s" % tuple(f3(x) for x in h) for h in hr))
            if r.get("epoch"):
                P("              dev-selected epoch %s; dev %s; train %s; final-epoch test %s" % (
                    "/".join(str(x) for x in r["epoch"]), "/".join(f3(x) for x in r["dev"]),
                    "/".join(f3(x) for x in r["train"]), "/".join(f3(x) for x in r["final"])))
    P("\n## Bar (registered): MATCH = mean recovery >= 0.90 on both encoders")
    match = [k for k in LF if all(verdict.get((e, k), (None, ""))[1].startswith("MATCH") for e in ENCS)]
    for k in LF:
        P("  %-8s %s" % (k, "  |  ".join("%s %s (R %s)" % (ENCN[e], verdict.get((e, k), (None, "missing"))[1],
                                                          f3(verdict.get((e, k), (None, ""))[0])) for e in ENCS)))
    ans = "YES" if match else "NO"
    allfail = all(verdict.get((e, k), (None, ""))[1] == "FAIL" for e in ENCS for k in LF)
    P("  ANSWER A: with one surface form per symbol, a label-free interface reaches the naming head: %s%s" % (
        ans, (" (" + ", ".join(match) + ")") if match else (" (every arm FAIL on both encoders)" if allfail else "")))
    best = max(((verdict[(e, k)][0], e, k) for e in ENCS for k in LF if (e, k) in verdict and verdict[(e, k)][0] is not None),
               default=None)
    if best:
        P("  best label-free recovery: %s %s R %s" % (ENCN[best[1]], best[2], f3(best[0])))
    SC["A_answer"] = ans
    ia = load(a.indepA) if a.indepA else None
    if ia:
        P("\n## String hashing (second scorer, numpy; fixed random code per written form, no learning, threshold 0.5)")
        P("  arena C  (hexadecimal role, decimal filler): %s" % "/".join(f3(x) for x in ia["string_hash_C"]))
        P("  arena C1 (one decimal form)               : %s" % "/".join(f3(x) for x in ia["string_hash_C1"]))
        P("  C1 text parse equals the structure in %d / %d instances; parsed labels equal in %d" % (
            ia["C1_parse_equals_struct"], len(y), ia["C1_labels_equal"]))
        SC["A_string_hash"] = {"C": ia["string_hash_C"], "C1": ia["string_hash_C1"]}
    # predictions
    P("\n## Predictions (part A)")
    g = gates
    PRED["PA1"] = all(g.get("G0_" + e, False) for e in ENCS) and all(g.get("G1_%s_%s" % (e, f), False) for e in ENCS for f in ("gumbel", "st"))
    nm = {e: RES.get((e, "name")) for e in ENCS}
    ex = RES.get(("X", "exact"))
    PRED["PA2"] = bool(nm["phi2"] and nm["qwen8"] and ex and nm["phi2"]["mean"] >= 0.98 and nm["qwen8"]["mean"] >= 0.95
                       and all(x >= 0.99 for x in ex["acc"]))
    PRED["PA3"] = all(RES.get((e, "probe")) and RES[(e, "probe")]["mean"] <= 0.60 for e in ENCS)
    PRED["PA4"] = not any(verdict.get((e, k), (None, ""))[1].startswith("MATCH") for e in ENCS for k in LF)
    below = [(e, k) for e in ENCS for k in LF if verdict.get((e, k), (None, ""))[0] is not None and verdict[(e, k)][0] >= 0.25]
    PRED["PA5"] = len(below) <= 1
    b6 = []
    for e in ENCS:
        r = RES.get((e, "bind"))
        if r:
            Rm, _, _ = rec_ci(r, RES.get((e, "probe")), RES.get((e, "name")))
            b6.append(all(gg and gg["different"] >= 0.50 for gg in r["geom"]) and Rm is not None and Rm < 0.25)
    PRED["PA6"] = len(b6) == 2 and all(b6)
    if ia:
        PRED["PA7"] = all(x <= 0.60 for x in ia["string_hash_C"]) and all(x >= 0.99 for x in ia["string_hash_C1"])
    pa8 = []
    for e in ENCS:
        for fam in ("vq", "dkvb"):
            r = RES.get((e, fam))
            if r and r.get("disc") and r["disc"][0]:
                pa8.append(all(d["consistency"] <= 0.60 for d in r["disc"]))
    PRED["PA8"] = bool(pa8) and all(pa8)
    txt = {"PA1": "gates G0 and G1 pass on both encoders", "PA2": "naming head >= 0.98 (Phi-2) / >= 0.95 (Qwen3-8B); exact >= 0.99 per seed",
           "PA3": "probe <= 0.60 on both encoders", "PA4": "no label-free arm MATCHES on either encoder",
           "PA5": "every label-free recovery < 0.25 except at most one cell (cells >= 0.25: %s)" % (below or "none"),
           "PA6": "binding-loss map COLLAPSES (different >= 0.50, 3/3 seeds) and FAILS on both encoders",
           "PA7": "string hash: C <= 0.60 per seed, C1 >= 0.99", "PA8": "vq / dkvb mention consistency <= 0.60 every seed"}
    for k in sorted(txt):
        if k in PRED:
            P("  %s %s: %s" % (k, txt[k], held(PRED[k])))
    return RES


# ====================================================================== part B

def part_b(a, SC, PRED):
    R = os.path.join(a.root, "b")
    P("\n# PART B: naming where identity is not in the surface string (alias stories), test")
    sel = load(os.path.join(R, "select.json")) or {}
    for kind in "WP":
        if kind in sel:
            P("  head selection %s: layer %d, lr %g, dev chain-naming %.4f (epoch %d); grid: %s" % (
                kind, sel[kind]["layer"], sel[kind]["lr"], sel[kind]["dev"], sel[kind]["epoch"],
                "; ".join("L%d/%g %.3f" % (r["layer"], r["lr"], r["dev"]) for r in sel[kind + "_grid"])))
    out = {}
    for kind in "WP":
        d = load(os.path.join(R, "scores_%s_test.json" % kind))
        if d is None:
            P("\n  %s: scores missing" % kind); continue
        st = S48.build_B(kind, "test")
        y = np.array([s["label"] for s in st])
        assert y.tolist() == d["labels"]
        hard = "alias" if kind == "W" else "pron"
        mt = d["mtypes"]
        types = [t for t in ("roster", "can", hard, "ante", "q", "cand") if t in mt]
        P("\n## %s (%s), n = %d stories, %d mentions per story (%s)" % (
            kind, "Wikidata aliases" if kind == "W" else "pronouns", len(y), len(mt),
            ", ".join("%s %d" % (t, mt.count(t)) for t in types)))
        res = {}
        for arm, rows in d["arms"].items():
            C = np.array([((np.array(r["scores"]) >= 0.5).astype(int) == y).astype(int) for r in rows])
            acc = C.mean(1)
            logged_ok = all(abs(x - r["acc"]) < 1e-9 for x, r in zip(acc, rows))
            bm = boot_means(C)
            Nm = np.array(rows[0]["named"]) if arm != "head" else np.stack([np.array(r["named"]) for r in rows])
            res[arm] = {"C": C, "acc": acc.tolist(), "mean": float(acc.mean()), "bm": bm, "ci": ci(bm),
                        "wilson": [wilson(int(c.sum()), len(c)) for c in C], "logged_ok": logged_ok, "named": Nm,
                        "h1": [float(np.mean(r["hop1_ok"])) for r in rows], "h2": [float(np.mean(r["hop2_ok"])) for r in rows]}
        hs, orc = res.get("hash"), res.get("oracle")
        for arm in ("oracle", "hash", "lm", "head"):
            if arm not in res:
                P("    %-6s NOT RUN / missing" % arm); continue
            r = res[arm]
            P("    %-6s end accuracy mean %s [%s-%s]  seeds %s%s" % (
                arm, f3(r["mean"]), f3(r["ci"][0]), f3(r["ci"][1]),
                ", ".join("%s [%s-%s]" % (f3(x), f3(w[0]), f3(w[1])) for x, w in zip(r["acc"], r["wilson"])),
                "" if r["logged_ok"] else "  RECOMPUTED != LOGGED"))
            P("           clean-up correct hop 1 / hop 2: %s" % ", ".join("%s/%s" % (f3(u), f3(v)) for u, v in zip(r["h1"], r["h2"])))
            Nm = r["named"]
            parts = []
            for t in types:
                cols = [i for i, x in enumerate(mt) if x == t]
                if Nm.ndim == 3:                                   # head: per seed
                    vals = [float(Nm[s][:, cols].mean()) for s in range(Nm.shape[0])]
                    parts.append("%s %s" % (t, "/".join(f3(v) for v in vals)))
                else:
                    parts.append("%s %s" % (t, f3(float(Nm[:, cols].mean()))))
            P("           naming accuracy per mention type: %s" % "; ".join(parts))
            cols = [i for i, x in enumerate(mt) if x == hard]
            M2 = Nm if Nm.ndim == 2 else Nm.mean(0)
            per_story = M2[:, cols].mean(1)
            idx = boot_idx(len(per_story))
            bsn = per_story[idx].mean(1)
            k_ = int(Nm[..., cols].sum()) if Nm.ndim == 2 else int(Nm[0][:, cols].sum())
            n_ = len(cols) * Nm.shape[-2]
            r["hard"] = float(M2[:, cols].mean()); r["hard_ci"] = ci(bsn)
            P("           %s naming %s [story bootstrap %s-%s]%s" % (
                hard, f3(r["hard"]), f3(r["hard_ci"][0]), f3(r["hard_ci"][1]),
                "; Wilson (seed 42) %s-%s" % tuple(f3(x) for x in wilson(k_, n_))))
            if hs and orc and arm in ("lm", "head"):
                Rm = (r["mean"] - hs["mean"]) / (orc["mean"] - hs["mean"])
                bs = (r["bm"] - hs["bm"]) / (orc["bm"] - hs["bm"])
                Rci = ci(bs)
                r["R"], r["Rci"] = Rm, Rci
                b = "MATCH" if Rm >= 0.90 else ("PARTIAL" if Rm >= 0.25 else "FAIL")
                r["bar"] = b
                P("           recovery R_B = (mean - hash) / (oracle - hash) %s [%s, %s] -> %s; names the hard mentions "
                  "(>= 0.90): %s" % (f3(Rm), f3(Rci[0]), f3(Rci[1]), b, "YES" if r["hard"] >= 0.90 else "NO"))
            SC["B_%s_%s" % (kind, arm)] = {k: r[k] for k in ("acc", "mean", "ci", "hard", "hard_ci") if k in r}
            SC["B_%s_%s" % (kind, arm)].update({k: r[k] for k in ("R", "Rci", "bar") if k in r})
        if "lm" in res and "head" in res:
            dlt = res["head"]["bm"] - res["lm"]["bm"]
            P("    head - lm end accuracy %+.3f [%+.3f, %+.3f]" % (res["head"]["mean"] - res["lm"]["mean"], *ci(dlt)))
            cols = [i for i, x in enumerate(mt) if x == hard]
            ph = res["head"]["named"].mean(0)[:, cols].mean(1); pl = res["lm"]["named"][:, cols].mean(1)
            idx = boot_idx(len(ph))
            dd = (ph - pl)[idx].mean(1)
            P("    head - lm %s naming %+.3f [%+.3f, %+.3f]" % (hard, float((ph - pl).mean()), *ci(dd)))
            SC["B_%s_head_minus_lm" % kind] = {"end": [float(res["head"]["mean"] - res["lm"]["mean"]), ci(dlt)],
                                               "hard_naming": [float((ph - pl).mean()), ci(dd)]}
        if "lm_parsed_lines" in d:
            pl = np.array(d["lm_parsed_lines"])
            lw = d["lm_written"]
            names = [set(e["name"] for e in s["ents"]) for s in st]
            ex = [sum(1 for v in w.values() if v is not None and v in nm) / max(1, len(w)) for w, nm in zip(lw, names)]
            P("    lm: parsed lines per story mean %.2f of 28 (all 28 in %d / %d stories); written names exactly a listed "
              "name %.3f" % (pl.mean(), int((pl == 28).sum()), len(pl), float(np.mean(ex))))
            # descriptive (added after the dev check of compute note 5, not a bar): what the LM wrote for hard mentions
            from collections import Counter
            cnt = Counter()
            for i, s in enumerate(st):
                listed = set(S48.norm(e["name"]) for e in s["ents"])
                for mi, m in enumerate(s["mentions"]):
                    if m[4] != hard:
                        continue
                    w = lw[i].get(str(mi))
                    if w is None:
                        cnt["missing"] += 1
                    elif S48.norm(w) == S48.norm(s["ents"][m[1]]["name"]):
                        cnt["the right listed name"] += 1
                    elif S48.norm(w) == S48.norm(s["text"][m[2]:m[3]]):
                        cnt["copied as written"] += 1
                    elif S48.norm(w) in listed:
                        cnt["another listed name"] += 1
                    else:
                        cnt["another string"] += 1
            tot = sum(cnt.values())
            P("    lm, what it wrote for the %d %s mentions: %s" % (tot, hard, "; ".join(
                "%s %d (%.3f)" % (k, v, v / tot) for k, v in cnt.most_common())))
            SC["B_%s_lm_written_breakdown" % kind] = dict(cnt)
        out[kind] = res
    P("\n## Predictions (part B)")
    W, Pp = out.get("W", {}), out.get("P", {})

    def ok(d, k):
        return k in d
    if ok(W, "oracle") and ok(Pp, "oracle"):
        PRED["PB1"] = all(x >= 0.99 for x in W["oracle"]["acc"] + Pp["oracle"]["acc"]) and \
            all(x <= 0.62 for x in W["hash"]["acc"] + Pp["hash"]["acc"])
    mt = {k: load(os.path.join(R, "scores_%s_test.json" % k)) for k in "WP"}

    def can(d, arm, kind):
        m = mt[kind]["mtypes"]; cols = [i for i, x in enumerate(m) if x in ("can", "q", "cand")]
        Nm = d[arm]["named"]
        return float((Nm if Nm.ndim == 2 else Nm.mean(0))[:, cols].mean())
    if ok(W, "lm") and ok(Pp, "lm"):
        PRED["PB2"] = Pp["lm"]["hard"] >= 0.95 and 0.40 <= W["lm"]["hard"] <= 0.85 and can(W, "lm", "W") >= 0.98 and can(Pp, "lm", "P") >= 0.98
    if ok(W, "head") and ok(Pp, "head"):
        PRED["PB3"] = Pp["head"]["hard"] >= 0.90 and W["head"]["hard"] <= 0.60 and can(W, "head", "W") >= 0.97 and can(Pp, "head", "P") >= 0.97
    if all(ok(x, y_) for x in (W, Pp) for y_ in ("lm", "head")):
        PRED["PB4"] = Pp["head"]["bar"] == "MATCH" and Pp["lm"]["bar"] == "MATCH" and W["head"]["bar"] in ("FAIL", "PARTIAL") \
            and W["lm"]["bar"] == "PARTIAL"
        hm = SC.get("B_W_head_minus_lm")
        PRED["PB5"] = bool(hm) and hm["end"][1][1] < 0
    if "W" in sel:
        PRED["PB6"] = sel["W"]["layer"] in (9, 18, 27)
    txt = {"PB1": "oracle >= 0.99 and hash <= 0.62 per seed on W and P",
           "PB2": "lm naming: P pronouns >= 0.95, W aliases in [0.40, 0.85], listed-name mentions >= 0.98",
           "PB3": "head naming: P pronouns >= 0.90, W aliases <= 0.60, listed-name mentions >= 0.97",
           "PB4": "P: head and lm MATCH; W: head FAIL/PARTIAL, lm PARTIAL", "PB5": "W: lm end accuracy > head (interval excludes 0)",
           "PB6": "dev-selected head layer on W is 9, 18 or 27"}
    for k in sorted(txt):
        if k in PRED:
            P("  %s %s: %s" % (k, txt[k], held(PRED[k])))
    return out


