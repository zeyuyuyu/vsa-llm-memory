"""B47 hand-reading material (prereg/B47_phi2_finetunes_hierboot_consistency_prereg.md): for the best new Phi-2
fine-tune at 800 (and 8,000 if run), the first 12 test failures of seed 42 with the raw text's question, the dictionary
walk (bridge, answer), whether the candidate is a table-F filler (the shortcut), the model's margin / generation; and
12 sweep failures (seed 42, perm, mention model, the level nearest s = 0.30) with the hop that failed. Written to
results/b47_handread.txt; the reading notes are added by hand below the generated part.

  python b47_handread.py
"""
import json, os, re, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
R = os.path.join(HERE, "b47_out")


def main():
    import b44_data as BD
    st = BD.split("std", "test", struct=False)
    L = ["# B47 hand-reading material (generated by b47_handread.py)"]
    sp_ = os.path.join(R, "select.json")
    sel = json.load(open(sp_)) if os.path.exists(sp_) else {}
    for key in ("gen_k32_n800", "fullgen_k32_n800", "fullcls_k32_n800", "scratch_k32_n800", "gen_std_n8000",
                "fullgen_std_n8000"):
        s = sel.get(key)
        if not s:
            continue
        task, variant, n = key.split("_")[0], key.split("_")[1], int(key.split("_")[2][1:])
        p = os.path.join(R, "ft", "%s_%s_n%d_r%d_lr%s_s42.json.test.json" % (task, variant, n, s["rank"], "%g" % s["lr"]))
        if not os.path.exists(p):
            continue
        t = json.load(open(p))["test"]
        L.append("\n## %s (rank %d, lr %g), seed 42: test acc %.3f" % (key, s["rank"], s["lr"], t["acc"]))
        k = 0
        for i, inst in enumerate(st):
            d = BD.dict_answer(inst["text"])
            F_vals = {int(b) for a, b in re.findall(r"\[F([0-9A-F]{2})\]\{(\d+)\}", inst["text"])}
            if task == "scratch":
                import b44_lora as BL
                g = t["gens"][i]; pred = BL.parse_scratch(g)[0]; out = "gen %r" % g
            else:
                sc = t["scores"][i]; pred = int(sc > 0); out = "margin %+.3f" % sc
            if pred == d["label"]:
                continue
            q = re.search(r"Q \[R[0-9A-F]{2}\] \{\d+\} \?", inst["text"]).group(0)
            L.append("  #%d %s label %d: query R%02X -> bridge %d (= F%02X) -> answer %d; candidate %d (%s a table-F filler); "
                     "%s" % (i, q, d["label"], d["q"], d["bridge"], d["bridge"], d["answer"], d["cand"],
                             "is" if d["cand"] in F_vals else "is NOT", out))
            k += 1
            if k >= 12:
                break
    sw = os.path.join(R, "sweep_consistency.json")
    if os.path.exists(sw):
        S = json.load(open(sw))
        rows = [x for x in S["cells"] if x["structure"] == "mention" and x["enc"] == "perm"]
        x = min(rows, key=lambda r: abs(r["geom_same_mean"] - 0.30))
        r42 = [r for r in x["per_seed"] if r["seed"] == 42][0]
        y = np.array([BD.dict_answer(s["text"])["label"] for s in st])
        dec = (np.array(r42["test_scores"]) >= r42["thr"]).astype(int)
        both = np.array(r42["test_both_hops_right"])
        L.append("\n## sweep (perm, mention), rho %.2f (measured same-symbol cosine %.3f), seed 42: acc %.3f, threshold %.3f"
                 % (x["rho"], x["geom_same_mean"], r42["acc"], r42["thr"]))
        k = 0
        for i in range(len(y)):
            if dec[i] == y[i]:
                continue
            L.append("  #%d label %d, final score %.3f, both hops right %d" % (i, y[i], r42["test_scores"][i], both[i]))
            k += 1
            if k >= 12:
                break
        fails = dec != y
        L.append("  failures: %d; of them with both hops right %d (score-threshold errors), with a hop wrong %d" % (
            fails.sum(), (fails & (both == 1)).sum(), (fails & (both == 0)).sum()))
        L.append("  positives with a hop wrong: %d of %d positives; negatives with a hop wrong: %d of %d" % (
            ((y == 1) & (both == 0)).sum(), (y == 1).sum(), ((y == 0) & (both == 0)).sum(), (y == 0).sum()))
    open(os.path.join(HERE, "results", "b47_handread.txt"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
