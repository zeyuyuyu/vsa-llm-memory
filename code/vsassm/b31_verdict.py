def f3(x):
    return "%.3f" % x if x is not None and x == x else "n/a"


def load(p):
    if os.path.exists(p):
        return json.load(open(p))
    if os.path.exists(p + ".gz"):
        return json.load(gzip.open(p + ".gz", "rt"))
    return None


def wilson(k, n, z=1.96):
    p = k / n; d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def boot_mean(C, B=10000, seed=0):
    C = np.asarray(C, float); n = C.shape[1]
    idx = np.random.default_rng(seed).integers(0, n, size=(B, n))
    m = C[:, idx].mean(axis=2).mean(axis=0)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def boot_diff(A, Bm, B=10000, seed=1):
    A = np.asarray(A, float); Bm = np.asarray(Bm, float); n = A.shape[1]
    idx = np.random.default_rng(seed).integers(0, n, size=(B, n))
    d = A[:, idx].mean(axis=2).mean(axis=0) - Bm[:, idx].mean(axis=2).mean(axis=0)
    return float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))


# ------------------------------------------------------------------ recomputation from saved outputs

def sel_epoch(run, reading):
    k = "%s:dev" % reading
    accs = [e[k]["acc"] for e in run["epochs"]]
    return max(range(len(accs)), key=lambda j: (accs[j], -j))


def memory_arm(root, pat, enc, ar, reading, y):
    d = load(os.path.join(root, pat.format(enc=enc, ar=ar)))
    if d is None:
        return None
    out = {"acc": [], "C": [], "logged": [], "geom": [], "epoch": [], "naming": [], "final": [], "train": []}
    for run in d["runs"]:
        j = sel_epoch(run, reading)
        e = run["epochs"][j]["%s:test" % reading]
        pred = (np.array(e["scores"]) >= e["thr"]).astype(int)
        c = (pred == y).astype(int)
        out["C"].append(c); out["acc"].append(float(c.mean())); out["logged"].append(e["acc"])
        out["epoch"].append(run["epochs"][j]["epoch"]); out["train"].append(e["train_acc"])
        out["geom"].append(e.get("geom") or run["epochs"][j].get("%s:test" % PRIMARY, {}).get("geom"))
        out["naming"].append(e.get("naming_acc_mentions"))
        out["final"].append(run["epochs"][-1]["%s:test" % reading]["acc"])
    out["seeds"] = [r["seed"] for r in d["runs"]]
    return out


def probe_arm(root, enc, ar, y):
    d = load(os.path.join(root, "probe_final/%s_%s.json" % (enc, ar)))
    if d is None:
        return None
    out = {"acc": [], "C": [], "logged": [], "sel": d["selected"]}
    for r in d["runs"]:
        c = (((np.array(r["test_scores"]) > 0).astype(int)) == y).astype(int)
        out["C"].append(c); out["acc"].append(float(c.mean())); out["logged"].append(r["test_acc"])
    return out


def lora_arm(root, enc, ar, idl, y):
    out = {"acc": [], "C": [], "logged": [], "train_max": [], "epoch": [], "id_acc": [], "pos_rate": []}
    for s in SEEDS:
        d = load(os.path.join(root, "lora_final/%s_%s_id%d_s%d.json" % (enc, ar, idl, s)))
        if d is None:
            return None
        r = d["runs"][0]
        c = (((np.array(r["test_scores"]) > 0).astype(int)) == y).astype(int)
        out["C"].append(c); out["acc"].append(float(c.mean())); out["logged"].append(r["test"]["acc"])
        out["train_max"].append(max(e["train_sub"]["acc"] for e in r["epochs"])); out["epoch"].append(r["best_epoch"])
        out["id_acc"].append(r["test"].get("id_acc_mentions")); out["pos_rate"].append(r["test"]["pos_rate"])
    return out


def summarise(res):
    C = np.array(res["C"])
    res["mean"] = float(C.mean(axis=1).mean())
    res["ci"] = boot_mean(C)
    n = C.shape[1]
    res["wilson"] = [wilson(int(c.sum()), n) for c in C]
    res["recomputed_equals_logged"] = all(abs(a - b) < 1e-9 for a, b in zip(res["acc"], res["logged"]))
    return res


def margin_reading(Na, Ba, CN, CB):
    m = [a - b for a, b in zip(Na, Ba)]
    M = float(np.mean(Na) - np.mean(Ba))
    ci = boot_diff(CN, CB)
    if M >= 0.10 and all(x >= 0.10 for x in m):
        o = "STANDS"
    elif M <= 0.03:
        o = "CLOSED"
    else:
        o = "NARROWED"
    return M, m, ci, o


def recov(acc, F_, Cl):
    if Cl - F_ < 0.10:
        return None
    return (acc - F_) / (Cl - F_)


def lf_bar(rs):
    if rs is None or any(r is None for r in rs):
        return "no headroom"
    mr = float(np.mean(rs))
    if mr >= 0.90 and all(r >= 0.80 for r in rs):
        return "MATCH"
    return "PARTIAL" if mr >= 0.25 else "FAIL"


def ledger(path):
    if not os.path.exists(path):
        return [], 0.0, {}
    st, rows = {}, []
    for l in open(path):
        p = l.split()
        if len(p) != 4:
            continue
        name, gpu, kind, t = p
        t = datetime.strptime(t, "%Y-%m-%dT%H:%M:%SZ")
        if kind == "start":
            st[(name, gpu)] = t
        elif (name, gpu) in st:
            h = (t - st.pop((name, gpu))).total_seconds() / 3600
            rows.append((name, gpu, h))
    return rows, sum(r[2] for r in rows), st


