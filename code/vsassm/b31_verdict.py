    pr("P9 equalised probe: A and C means <= 0.60 on both encoders; B >= 0.90 on both",
       all((m_(e, ar, "probe") or 1) <= 0.60 for e in ENCS for ar in "AC") and
       all((m_(e, "B", "probe") or 0) >= 0.90 for e in ENCS))
    pr("P10 Phi-2 equalised LoRA: A and C <= 0.65, B >= 0.95",
       all((m_("phi2", ar, "lora") or 1) <= 0.65 for ar in "AC") and (m_("phi2", "B", "lora") or 0) >= 0.95)
    pr("P11 Qwen3-8B equalised LoRA: A <= 0.80, C <= 0.70, B >= 0.97",
       (m_("qwen8", "A", "lora") or 1) <= 0.80 and (m_("qwen8", "C", "lora") or 1) <= 0.70 and
       (m_("qwen8", "B", "lora") or 0) >= 0.97)
