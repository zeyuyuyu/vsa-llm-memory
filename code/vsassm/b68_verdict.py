"""B68 verdict (prereg/B68_early_layer_labelfree_prereg.md). Written before any B68 test output exists.

The seven B42 label-free interfaces and B31's binding-loss map on the input embeddings (L0) and early layers (L2, L4) of
Phi-2 and Qwen3-8B, arenas A, B, C, against the naming head read from the SAME layer. Every test accuracy is recomputed
from the saved per-instance outputs against labels regenerated by b31_struct (b42_verdict.memory_arm / probe_arm) and
compared with the logged value. F = B31's equalised probe (final layer; the floor of B42 / B52); N = the naming head
(perm, named) at the cell's layer (B68 run, B31 explore1 arguments). Reference without training: the feature-hash
reader (one fixed random code per distinct span-feature vector; the published chain; the closed-form threshold from
the training split).

  python b68_verdict.py --root out --b31 /path/to/work/b31/out --feats feats --out b68_verdict.txt --scores b68_scores.json
"""
import argparse, json, os, sys
from datetime import datetime

import numpy as np
import torch
import torch.nn.functional as F

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import b31_arms as B                                                        # noqa: E402
import b31_struct as S                                                      # noqa: E402
import b42_verdict as V                                                     # noqa: E402
from b68_queues import ORDER, FAMS                                          # noqa: E402

LF = ["vq", "dkvb", "gumbel", "st", "cw", "bind+pc", "bind+pz", "bind"]
PRIMARY = "perm/named"
LAYER = {"0": "input embeddings (L0)", "2": "layer 2", "4": "layer 4"}
MODEL = {"phi2": "Phi-2", "qwen8": "Qwen3-8B"}
L = []


def P(s=""):
    L.append(s); print(s)


def hash_reader(enc, ar, feats, y_test):
    """Feature-hash reader: identical span-feature vectors get one fixed random code (seed 4242), distinct ones unrelated
    codes; threshold fitted on the training split's scores (closed form), applied to test."""
    keyb = {}
    out = {}
    m = B.Arm(ar, "exact", 42, 8)
    g = torch.Generator().manual_seed(4242)
    for sp in ("train", "test"):
        obj = torch.load(os.path.join(feats, "%s_%s_%s.pt" % (enc, ar, sp)), weights_only=False)
        Fm = obj["F"]
        N, M, d = Fm.shape
        flat = Fm.reshape(-1, d).numpy()
        vid = np.array([keyb.setdefault(hash(flat[i].tobytes()), len(keyb)) for i in range(flat.shape[0])]).reshape(N, M)
        out[sp] = (vid, obj["labels"].numpy())
    T = F.normalize(torch.randn(len(keyb), B.D, generator=g), dim=-1)
    sc = {}
    with torch.no_grad():
        for sp in ("train", "test"):
            vid = out[sp][0]
            s_ = []
            for k in range(0, vid.shape[0], 64):
                K = T[torch.tensor(vid[k:k + 64])]
                if ar == "A":
                    K = B.l2n(K)
                s_.append(m.chain(K, "perm")[0])
            sc[sp] = torch.cat(s_).numpy()
    acc, thr, tracc = B.thr_acc(sc["train"], out["train"][1], sc["test"], y_test)
    c = ((sc["test"] >= thr).astype(int) == y_test).astype(int)
    r = V.summarise({"acc": [float(c.mean())], "C": [c], "logged": [float(c.mean())]})
    r["train_acc"] = tracc
    return r


def ledger(path):
    rows, st = [], {}
    if not os.path.exists(path):
        return rows, 0.0
    for l in open(path):
        p = l.split()
        if len(p) < 4 or p[2] not in ("start", "end"):
            continue
        t = datetime.strptime(p[3], "%Y-%m-%dT%H:%M:%SZ")
        if p[2] == "start":
            st[(p[0], p[1])] = t
        elif (p[0], p[1]) in st:
            rows.append((p[0], p[1], (t - st.pop((p[0], p[1]))).total_seconds() / 3600))
    return rows, sum(r[2] for r in rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="out")
    ap.add_argument("--b31", default="/path/to/work/b31/out")
    ap.add_argument("--feats", default="feats")
    ap.add_argument("--out", default="b68_verdict.txt")
    ap.add_argument("--scores", default="b68_scores.json")
    ap.add_argument("--cut", default="", help="cells cut by a compute note (reported as not run)")
    ap.add_argument("--ledger", default="logs/gpu_ledger.txt")
    a = ap.parse_args()
    cut = set(x for x in a.cut.split(",") if x)
    R, R31 = a.root, a.b31
    cells = [c for c in ORDER if "%s_%s" % c not in cut]
    P("# B68 verdict (prereg/B68_early_layer_labelfree_prereg.md): label-free readers of the input embeddings and early")
    P("# layers of Phi-2 and Qwen3-8B. Generated by b68_verdict.py on %s UTC." % datetime.utcnow().strftime("%Y-%m-%d %H:%M"))
    P("# Cells reported: %d; NOT RUN (cut by compute note, no test output read): %s" % (len(cells), ", ".join(sorted(cut)) or "none"))
    ST = {ar: S.build(ar, "test") for ar in "ABC"}
    Y = {ar: np.array([s["label"] for s in ST[ar]]) for ar in "ABC"}
    sel = V.load(os.path.join(R, "select.json")) or {}
    out = {"cells": {}}
    P("\n## Dev selections (seed 42, train + dev only; best-epoch dev accuracy, perm/named)")
    for enc, ar in cells:
        k = "%s_%s" % (enc, ar)
        b = sel.get("bind", {}).get(k)
        if b:
            P("  %-10s binding-loss lr %g (dev %s)" % (k, b["pick"]["cfg"]["lr"], ", ".join(
                "lr %g %.3f" % (r["cfg"]["lr"], r["dev"]) for r in b["rows"])))
        for fam in FAMS:
            v = sel.get(fam, {}).get(k)
            if v:
                P("  %-10s %-7s %s dev %.3f (epoch %d) of %d configurations" % (
                    k, fam, json.dumps(v["cfg"]), v["dev"], v["epoch"], len(sel["grids"][fam][k])))
    P("\n## Gate G1 (labelled positive control, dev): gumbel / st code path + identity loss within 0.02 of the")
    P("## naming head's best dev on the same cell")
    for enc, ar in cells:
        k = "%s_%s" % (enc, ar)
        nm = V.load(os.path.join(R, "name", "%s_name.json" % k))
        ndev = max(e["%s:dev" % PRIMARY]["acc"] for e in nm["runs"][0]["epochs"]) if nm else None
        for fam in ("gumbel", "st"):
            g1 = V.load(os.path.join(R, "g1", "%s_%s_g1.json" % (k, fam)))
            if g1 and ndev is not None:
                gd = max(e["%s:dev" % PRIMARY]["acc"] for e in g1["runs"][0]["epochs"])
                ok = gd >= ndev - 0.02
                out.setdefault("G1", {})["%s_%s" % (k, fam)] = ok
                P("  G1 %-10s %-6s best dev %.3f vs naming head %.3f  %s" % (k, fam, gd, ndev, "PASS" if ok else "FAIL"))
    P("\n## Results: test accuracy per seed (42/123/456) [Wilson 95%], mean [bootstrap 95%]; recovery R = (mean - F) /")
    P("## (N - F); F = B31 equalised probe (final layer), N = naming head (perm, named) read from the SAME layer")
    BAR, SUM = {}, []
    for enc, ar in cells:
        k = "%s_%s" % (enc, ar)
        mdl, lay = enc.split("L")
        y = Y[ar]
        Fr = V.probe_arm(os.path.join(R31, "probe_final", "%s_%s.json" % (mdl, ar)), y)
        Nr = V.memory_arm(os.path.join(R, "name", "%s_name.json" % k), PRIMARY, y)
        others = {"final": os.path.join(R31, "arms_final", "%s_%s_name.json" % (mdl, ar))}
        if mdl == "qwen8":
            for LL in (9, 18, 27):
                others["L%d" % LL] = os.path.join(R31, "explore1", "qwen8L%d_%s_name.json" % (LL, ar))
        for LL in (0, 2, 4):
            others["L%d (B68)" % LL] = os.path.join(R, "name", "%sL%d_%s_name.json" % (mdl, LL, ar))
        Nall = {kk: V.memory_arm(p, PRIMARY, y) for kk, p in others.items()}
        Nall = {kk: v for kk, v in Nall.items() if v}
        Nbest = max(Nall.items(), key=lambda kv: kv[1]["mean"]) if Nall else None
        P("\n  %s, %s, arena %s (n = %d)" % (MODEL[mdl], LAYER[lay], ar, len(y)))
        if not (Fr and Nr):
            P("    references missing"); continue
        gap = Nr["mean"] - Fr["mean"]
        P("    floor F %.3f, naming head at this layer N %.3f [%.3f-%.3f] (seeds %s), gap %.3f%s" % (
            Fr["mean"], Nr["mean"], Nr["ci"][0], Nr["ci"][1], "/".join(V.f3(x) for x in Nr["acc"]), gap,
            "" if gap >= 0.10 else " (< 0.10: no headroom, recovery undefined)"))
        P("    naming heads at other layers: " + ", ".join("%s %.3f" % (kk, v["mean"]) for kk, v in Nall.items())
          + "; best %s %.3f" % (Nbest[0], Nbest[1]["mean"]))
        if gap >= 0.10:
            P("    MATCH needs mean >= %.3f (with F at chance 0.5 instead: >= %.3f)" % (
                Fr["mean"] + 0.9 * gap, 0.5 + 0.9 * (Nr["mean"] - 0.5)))
        cell = {"F": Fr["mean"], "N": Nr["mean"], "N_ci": Nr["ci"], "N_seeds": Nr["acc"], "gap": gap,
                "N_best": [Nbest[0], Nbest[1]["mean"]], "arms": {}}
        try:
            H = hash_reader(enc, ar, a.feats, y)
            line = "    feature hash (no training; reference) %.3f [%.3f-%.3f] (train %.3f)" % (H["mean"], H["ci"][0], H["ci"][1], H["train_acc"])
            if gap >= 0.10:
                Rb = (H["bm"] - Fr["bm"]) / (Nr["bm"] - Fr["bm"])
                lo, hi = V.ci(Rb)
                line += "; recovery %.3f [%.3f, %.3f]" % ((H["mean"] - Fr["mean"]) / gap, lo, hi)
            P(line)
            cell["hash"] = {"mean": H["mean"], "ci": H["ci"], "train": H["train_acc"]}
        except Exception as ex:                                           # noqa: BLE001
            P("    feature hash: not computed (%s)" % ex)
        arms = {}
        for fam in FAMS:
            arms[fam] = V.memory_arm(os.path.join(R, "final", "%s_%s.json" % (k, fam)), PRIMARY, y)
        for rd, kk in ((PRIMARY, "bind"), (PRIMARY + "+pc", "bind+pc"), (PRIMARY + "+pz", "bind+pz")):
            arms[kk] = V.memory_arm(os.path.join(R, "final", "%s_bind.json" % k), rd, y)
        best = None
        for kk in LF:
            r = arms.get(kk)
            if r is None:
                P("    %-9s missing" % kk); continue
            line = "    %-9s mean %s [%s-%s]  seeds %s" % (kk, V.f3(r["mean"]), V.f3(r["ci"][0]), V.f3(r["ci"][1]), ", ".join(
                "%s [%s-%s]" % (V.f3(x), V.f3(w[0]), V.f3(w[1])) for x, w in zip(r["acc"], r["wilson"])))
            if not r["recomputed_equals_logged"]:
                line += "  RECOMPUTED != LOGGED (logged %s)" % "/".join(V.f3(x) for x in r["logged"])
            P(line)
            rec = {"mean": r["mean"], "ci": r["ci"], "seeds": r["acc"], "logged": r["logged"]}
            extra = []
            if gap >= 0.10:
                Rb = (r["bm"] - Fr["bm"]) / (Nr["bm"] - Fr["bm"])
                Rm = (r["mean"] - Fr["mean"]) / gap
                Rs = [(x - Fr["mean"]) / gap for x in r["acc"]]
                lo, hi = V.ci(Rb)
                b_ = V.bar(Rm, Rs)
                rec.update({"R": Rm, "R_ci": [lo, hi], "R_seeds": Rs, "bar": b_})
                BAR[(k, kk)] = (b_, Rm, (lo, hi))
                extra.append("recovery %.3f [%.3f, %.3f] (seeds %s) -> %s" % (Rm, lo, hi, "/".join("%.2f" % x for x in Rs), b_))
            else:
                BAR[(k, kk)] = ("no headroom", None, None)
                extra.append("vs floor %+.3f, vs naming head %+.3f (no headroom)" % (r["mean"] - Fr["mean"], r["mean"] - Nr["mean"]))
            Rf = (r["mean"] - 0.5) / (Nr["mean"] - 0.5) if Nr["mean"] - 0.5 >= 0.10 else None
            rec["R_chance"] = Rf
            extra.append("vs the naming head at this layer %+.3f; vs the best naming head (%s) %+.3f%s" % (
                r["mean"] - Nr["mean"], Nbest[0], r["mean"] - Nbest[1]["mean"],
                "; recovery with F at chance %.3f" % Rf if Rf is not None else ""))
            if r.get("geom") and r["geom"][0]:
                extra.append("cross-talk different/same " + ", ".join(
                    "%s/%s" % (V.f3(g["different"]), V.f3(g["same"])) if g else "-" for g in r["geom"]))
                rec["geom"] = r["geom"]
            if r.get("disc") and r["disc"][0]:
                ds = r["disc"]
                extra.append("mention consistency %s, code purity %s, codes used %s%s" % (
                    "/".join(V.f3(x["consistency"]) for x in ds), "/".join(V.f3(x["purity"]) for x in ds),
                    "/".join(str(x["codes_used"]) for x in ds),
                    ("; hex/decimal alias rate " + "/".join(V.f3(x.get("alias_rate")) for x in ds)) if ar == "C" else ""))
                rec["disc"] = ds
            if r.get("wins") and r["wins"][0] is not None and ar != "B":
                hr = [V.hop_rates(ar, ST[ar], w) for w in r["wins"]]
                extra.append("clean-up correct at hop 1 / hop 2 / both: " + ", ".join(
                    "%s/%s/%s" % (V.f3(h[0]), V.f3(h[1]), V.f3(h[2])) for h in hr if h))
                rec["hops"] = hr
            if r.get("epoch"):
                extra.append("dev-selected epoch %s; dev %s; train %s; final-epoch test %s" % (
                    "/".join(str(x) for x in r["epoch"]), "/".join(V.f3(x) for x in r["dev"]),
                    "/".join(V.f3(x) for x in r["train"]), "/".join(V.f3(x) for x in r["final"])))
            for x in extra:
                P("              %s" % x)
            cell["arms"][kk] = rec
            if best is None or r["mean"] > best[1]:
                best = (kk, r["mean"], rec.get("R"), rec.get("R_ci"))
        cell["best"] = best
        out["cells"][k] = cell
        SUM.append((mdl, lay, ar, Fr["mean"], Nr["mean"], gap, best, cell.get("hash", {}).get("mean")))
    P("\n## Bar per cell: a label-free reader MATCHES if its mean recovery is >= 0.90 (PARTIAL >= 0.25, FAIL < 0.25);")
    P("## no headroom if N - F < 0.10 (accuracies only)")
    ans = {}
    for enc, ar in cells:
        k = "%s_%s" % (enc, ar)
        rows = [(kk, BAR.get((k, kk))) for kk in LF]
        m = [kk for kk, r in rows if r and r[0].startswith("MATCHES")]
        p_ = [kk for kk, r in rows if r and r[0] == "PARTIAL"]
        nh = all(r and r[0] == "no headroom" for _, r in rows)
        ans[k] = {"match": m, "partial": p_, "no_headroom": nh, "complete": all(r for _, r in rows)}
        P("  %-10s %s" % (k, "; ".join("%s %s%s" % (kk, r[0], " (R %.3f [%.3f, %.3f])" % (r[1], r[2][0], r[2][1]) if r and r[1] is not None else "")
                                      if r else "%s n/a" % kk for kk, r in rows)))
        P("  %-10s -> %s%s" % ("", "no headroom" if nh else ("YES (" + ", ".join(m) + ")" if m else ("PARTIAL (" + ", ".join(p_) + ")" if p_ else "NO")),
                              "" if ans[k]["complete"] else " [incomplete]"))
    out["answer"] = ans
    P("\n## Summary (best label-free reader per cell; R = recovery of the probe-to-same-layer-naming-head gap)")
    P("  model     source  arena  F      N(same layer)  gap     best reader  mean   R [95%]                 hash")
    for mdl, lay, ar, Fm, Nm, gap, best, hm in SUM:
        P("  %-9s L%-6s %-6s %.3f  %.3f          %+.3f  %-11s  %s  %s  %s" % (
            MODEL[mdl], lay, ar, Fm, Nm, gap, best[0] if best else "-", V.f3(best[1]) if best else "-",
            ("%.3f [%.3f, %.3f]" % (best[2], best[3][0], best[3][1])) if best and best[2] is not None else "(no headroom)     ",
            V.f3(hm)))
    P("\n## Second scorer (b42_indep.py on the B68 finals; out/indep68.json)")
    ind = V.load(os.path.join(R, "indep68.json"))
    if ind:
        bad = {kk: v for kk, v in ind.items() if v.get("agreement", 1.0) < 0.99}
        P("  %d entries; discrete finals re-derived: %d; agreement < 0.99: %d" % (
            len(ind), sum(1 for v in ind.values() if "agreement" in v), len(bad)))
        for kk, v in sorted(ind.items()):
            P("  %-34s %s" % (kk, ", ".join("%s %s" % (x, V.f3(y) if isinstance(y, float) else y) for x, y in v.items())))
        out["indep"] = ind
    else:
        P("  missing")
    rows, tot = ledger(a.ledger)
    P("\n## Compute (logs/gpu_ledger.txt: GPU claimed from start to end of each worker)")
    for r in rows:
        P("  %-8s %-5s %.2f GPU-h" % r)
    P("  total %.2f A800 GPU-hours" % tot)
    out["gpu_hours"] = tot
    open(a.out, "w").write("\n".join(L) + "\n")
    json.dump(out, open(a.scores, "w"), indent=1, default=float)


if __name__ == "__main__":
    main()
